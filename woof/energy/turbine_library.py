def parametric_fraction(speeds: Any, specific_power_w_m2: float, *,
                        cp: float = PARAMETRIC_CP,
                        cut_in_ms: float = PARAMETRIC_CUT_IN_MS,
                        knee: float = PARAMETRIC_KNEE) -> np.ndarray:
    """Power fraction of a pitch-regulated rotor of the given specific power.

    ``s = 0.5 rho0 cp v^3 / SP`` and ``P/P_rated = s / (1 + s^n)^(1/n)``
    (``n = PARAMETRIC_KNEE``) from cut-in, 0 below; values within 0.1 % of
    rated are set to rated.  At reference density.
    """

    v = np.asarray(speeds, dtype=float)
    s = 0.5 * REFERENCE_DENSITY * cp * v ** 3 / float(specific_power_w_m2)
    fraction = s / (1.0 + s ** knee) ** (1.0 / knee)
    fraction = np.where(v < cut_in_ms, 0.0, fraction)
    return np.where(fraction >= 0.999, 1.0, fraction)


def parametric_speeds(cut_out_ms: float = PARAMETRIC_CUT_OUT_MS
                      ) -> np.ndarray:
    count = int(round(cut_out_ms / PARAMETRIC_STEP_MS)) + 1
    return np.round(np.linspace(0.0, cut_out_ms, count), 6)


def specific_power(capacity_mw: Any, rotor_diameter_m: Any) -> Any:
    """Rated power over swept area, W m-2 (same signature as
    ``woof.energy.ramps.specific_power``)."""

    result = np.asarray(capacity_mw, dtype=float) * 1e6 / (
        math.pi * np.asarray(rotor_diameter_m, dtype=float) ** 2 / 4.0)
    return float(result) if result.ndim == 0 else result


def rotor_for_specific_power(rated_kw: float, sp_w_m2: float) -> float:
    return math.sqrt(4.0 * rated_kw * 1000.0 / (math.pi * sp_w_m2))


@dataclass(frozen=True)
class TurbineCurve:
    """A power curve at 1.225 kg/m3 plus what is known about the machine."""

    curve_id: str
    manufacturer: str | None
    model: str
    rated_kw: float
    rotor_diameter_m: float
    speeds: np.ndarray = field(repr=False)
    power_kw: np.ndarray = field(repr=False)
    curve_source: str = "oedb"
    names: tuple[str, ...] = ()
    iec_class: str | None = None
    offshore: bool | None = None
    hub_heights_m: tuple[float, ...] = ()
    cut_out_ms: float = 25.0
    restart_ms: float | None = None
    gust_cut_out_ms: float | None = None
    source_url: str | None = None
    rotor_assumed: bool = False

    @property
    def restart(self) -> float:
        return (self.restart_ms if self.restart_ms is not None
                else self.cut_out_ms - RESTART_MARGIN_MS)

    @property
    def gust_limit(self) -> float:
        return (self.gust_cut_out_ms if self.gust_cut_out_ms is not None
                else self.cut_out_ms + GUST_MARGIN_MS)

    def fraction(self, speed: Any) -> np.ndarray:
        """Power / rated at reference-density speed ``speed``.

        Linear between points; zero below the first point and held at the
        last one above the curve.
        Cut-out is not applied here (it carries hysteresis; see
        ``woof.energy.power_farm.running_state``).  NaN in, NaN out.
        """

        speed = np.asarray(speed, dtype=float)
        out = np.interp(speed, self.speeds, self.power_kw,
                        left=0.0) / self.rated_kw
        return np.where(np.isfinite(speed), out, np.nan)

    def thrust_coefficient(self, speed: Any) -> np.ndarray:
        """Ct from the curve by 1-D momentum theory (pinned approximation).

        ``Cp = P / (0.5 rho0 A v^3 eta_d eta_r)`` with ``eta_d =
        DRIVETRAIN_EFFICIENCY`` and ``eta_r = ROTOR_EFFICIENCY``, capped
        just under the Betz limit; the axial induction ``a`` solves
        ``4 a (1 - a)^2 = Cp`` on ``[0, 1/3]`` and ``Ct = 4 a (1 - a)``
        (at most 8/9).  Zero where the curve gives no power.
        """

        v = np.asarray(speed, dtype=float)
        area = math.pi * self.rotor_diameter_m ** 2 / 4.0
        power_w = self.fraction(np.maximum(v, 0.0)) * self.rated_kw * 1000.0
        with np.errstate(divide="ignore", invalid="ignore"):
            cp = power_w / (0.5 * REFERENCE_DENSITY * area
                            * np.maximum(v, 1e-6) ** 3
                            * DRIVETRAIN_EFFICIENCY * ROTOR_EFFICIENCY)
        cp = np.clip(np.nan_to_num(cp, nan=0.0), 0.0, 16.0 / 27.0 * 0.999)
        lo = np.zeros_like(cp)
        hi = np.full_like(cp, 1.0 / 3.0)
        for _ in range(40):
            mid = 0.5 * (lo + hi)
            above = 4.0 * mid * (1.0 - mid) ** 2 > cp
            hi = np.where(above, mid, hi)
            lo = np.where(above, lo, mid)
        a = 0.5 * (lo + hi)
        return np.where(cp > 0.0, 4.0 * a * (1.0 - a), 0.0)


def generic_curve(rated_kw: float, *, rotor_m: float | None = None,
                  sp_w_m2: float | None = None, label: str,
                  iec_class: str | None = None,
                  offshore: bool | None = None,
                  cut_out_ms: float = PARAMETRIC_CUT_OUT_MS) -> TurbineCurve:
    """A parametric curve at a rating and either a rotor or an SP."""

    if rotor_m is None:
        if sp_w_m2 is None:
            raise TurbineLibraryRefused("generic curve needs a rotor or an SP")
        rotor_m = rotor_for_specific_power(rated_kw, sp_w_m2)
        assumed = True
    else:
        assumed = False
    sp = specific_power(rated_kw / 1000.0, rotor_m)
    speeds = parametric_speeds(cut_out_ms)
    return TurbineCurve(
        curve_id=label, manufacturer=None, model=label, rated_kw=rated_kw,
        rotor_diameter_m=rotor_m, speeds=speeds,
        power_kw=parametric_fraction(speeds, sp) * rated_kw,
        curve_source="generic", iec_class=iec_class, offshore=offshore,
        cut_out_ms=cut_out_ms, rotor_assumed=assumed)


