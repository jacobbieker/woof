"""Turbine-specific power curves and the rules that pick one for an asset.

``woof/data/energy/turbine_library.json`` (schema
``woof-energy.turbine-library.v1``) holds manufacturer power curves at the
IEC 61400-12-1 reference air density 1.225 kg/m3.  It is generated by
``tools/build_turbine_library.py`` from the Open Energy Platform wind turbine
library (via windpowerlib's ``oedb`` snapshot; ODbL-1.0, (c) Reiner Lemoine
Institut) plus a small table of manufacturer-published ratings and rotor
diameters for common models the snapshot lacks.  Entries are labelled with
``curve_source``:

``oedb``
    a measured/manufacturer power curve from the snapshot;
``parametric``
    the model's rated power and rotor diameter are known but its curve is
    not; the curve is :func:`parametric_fraction` at the model's specific
    power.

Matching an asset to a curve (:meth:`TurbineLibrary.match`) walks a fixed
ladder and records which rung answered (``match_quality``):

``exact``
    the asset's manufacturer and model, normalised by :func:`compact`
    (lower case, alphanumerics only, a trailing ``mw``/``kw`` unit dropped),
    equal one of an entry's names or aliases, with a compatible
    manufacturer (canonical names via the library's alias table);
``fuzzy``
    the model string parses (:func:`parse_model`) to the same rotor diameter
    (within ``FUZZY_ROTOR_TOLERANCE_M``) and rated power (within
    ``FUZZY_POWER_TOLERANCE``; the asset's rating stands in when the model
    string carries none) with a compatible family prefix, or failing a
    parse a ``difflib`` similarity of at least ``FUZZY_MIN_SIMILARITY``
    within the same manufacturer;
``size``
    the asset's rated power and rotor diameter are within
    ``SIZE_POWER_TOLERANCE`` and ``SIZE_ROTOR_TOLERANCE`` of an entry, the
    nearest in ``(ln P / 0.10, dD / D / 0.05)`` wins, with penalties for an
    IEC class or onshore/offshore disagreement and for a parametric curve;
``generic``
    a parametric curve at the asset's specific power when its rotor
    diameter is known, else the library's generic class curve (IEC I, II,
    III or offshore), scaled to the asset's rating;
``none``
    no rating could be found anywhere; power is NaN.

Everything here is deterministic: candidates are ranked by a score and then
by entry id.
"""

