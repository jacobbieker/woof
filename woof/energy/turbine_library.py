@dataclass(frozen=True)
class TurbineSpec:
    """What an asset says about its turbine (any field may be unknown)."""

    manufacturer: str | None = None
    model: str | None = None
    rated_kw: float | None = None
    rotor_diameter_m: float | None = None
    hub_height_m: float | None = None
    iec_class: str | None = None
    offshore: bool | None = None
    count: int | None = None


def _first_tag(tags: Mapping[str, str], keys: Sequence[str]) -> str | None:
    for key in keys:
        value = tags.get(key)
        if value is not None and str(value).strip():
            return str(value).strip()
    return None


def asset_offshore(asset: Asset) -> bool | None:
    for key in OFFSHORE_TAGS:
        if key in asset.tags:
            verdict = _truthy_offshore(key, asset.tags[key])
            if verdict is not None:
                return verdict
    return None


def spec_from_asset(asset: Asset, *, per_turbine: bool = True
                    ) -> TurbineSpec:
    """Read manufacturer/model/rating/rotor/hub/class/offshore from an asset.

    ``per_turbine`` says ``capacity_mw`` is one turbine's rating (a
    generator); for a plant it is the plant total and is not a rating.
    """

    tags = asset.tags
    rated = None
    if per_turbine and asset.capacity_mw is not None:
        rated = asset.capacity_mw * 1000.0
    if rated is None and per_turbine:
        for key in RATED_TAGS:
            if tags.get(key, "").strip():
                rated = parse_power_kw(tags[key], bare="kw" if key == "t_cap"
                                       else "auto")
                break
    rotor = asset.rotor_diameter_m or parse_length_m(
        _first_tag(tags, ROTOR_TAGS))
    hub = asset.hub_height_m or parse_length_m(_first_tag(tags, HUB_TAGS))
    count = None
    raw_count = _first_tag(tags, COUNT_TAGS)
    if raw_count is not None:
        try:
            count = int(float(raw_count))
        except ValueError:
            count = None
        if count is not None and count < 1:
            count = None
    return TurbineSpec(
        manufacturer=_first_tag(tags, MANUFACTURER_TAGS),
        model=_first_tag(tags, MODEL_TAGS),
        rated_kw=rated, rotor_diameter_m=rotor, hub_height_m=hub,
        iec_class=parse_iec_class(_first_tag(tags, IEC_TAGS)),
        offshore=asset_offshore(asset), count=count)


