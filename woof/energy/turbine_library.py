@dataclass(frozen=True)
class TurbineMatch:
    """The curve chosen for an asset and why."""

    quality: str
    curve: TurbineCurve | None
    score: float
    reason: str
    rated_kw: float | None

    def as_record(self) -> dict[str, Any]:
        curve = self.curve
        return {
            "match_quality": self.quality,
            "match_score": round(float(self.score), 4),
            "match_reason": self.reason,
            "curve_id": curve.curve_id if curve else None,
            "curve_source": curve.curve_source if curve else None,
            "curve_manufacturer": curve.manufacturer if curve else None,
            "curve_model": curve.model if curve else None,
            "curve_rated_kw": curve.rated_kw if curve else None,
            "rotor_diameter_m": (round(curve.rotor_diameter_m, 2)
                                 if curve else None),
            "rotor_assumed": bool(curve.rotor_assumed) if curve else None,
            "rated_kw": self.rated_kw,
        }


@dataclass
class TurbineLibrary:
    path: Path
    sha256: str
    license: str
    attribution: str
    curves: dict[str, TurbineCurve]
    manufacturer_aliases: dict[str, str]
    generic: dict[str, dict[str, Any]]
    generic_default: dict[str, str]
    _exact: dict[str, list[str]] = field(default_factory=dict, repr=False)
    _keys: dict[str, ModelKey] = field(default_factory=dict, repr=False)
    _canon: dict[str, str | None] = field(default_factory=dict, repr=False)

    def __post_init__(self):
        for curve_id, curve in sorted(self.curves.items()):
            canon = canonical_manufacturer(curve.manufacturer,
                                           self.manufacturer_aliases)
            self._canon[curve_id] = canon
            words = self._manufacturer_words(canon)
            self._keys[curve_id] = parse_model(curve.model, words)
            for name in (curve.model,) + curve.names:
                key = compact(name)
                if key:
                    self._exact.setdefault(key, [])
                    if curve_id not in self._exact[key]:
                        self._exact[key].append(curve_id)

    def __len__(self) -> int:
        return len(self.curves)

    def _manufacturer_words(self, canon: str | None) -> list[str]:
        if canon is None:
            return []
        words = {alias for alias, target in self.manufacturer_aliases.items()
                 if target == canon}
        words.add(canon.replace("-", " "))
        out: set[str] = set()
        for word in words:
            out.add(word)
            out.update(part for part in word.split() if len(part) > 2)
        return sorted(out)

    def get(self, curve_id: str) -> TurbineCurve:
        try:
            return self.curves[curve_id]
        except KeyError as error:
            raise TurbineLibraryRefused(
                f"turbine library {self.path} has no curve {curve_id!r}"
            ) from error

    # -- ladder ------------------------------------------------------------

    def match(self, spec: TurbineSpec) -> TurbineMatch:
        canon = canonical_manufacturer(spec.manufacturer,
                                       self.manufacturer_aliases)
        if spec.model:
            hit = self._match_exact(spec, canon)
            if hit is not None:
                return hit
            hit = self._match_fuzzy(spec, canon)
            if hit is not None:
                return hit
        if spec.rated_kw is not None and spec.rotor_diameter_m is not None:
            hit = self._match_size(spec)
            if hit is not None:
                return hit
        return self._match_generic(spec)

    def _compatible(self, canon: str | None, curve_id: str) -> bool:
        theirs = self._canon.get(curve_id)
        return canon is None or theirs is None or canon == theirs

    def _rated(self, spec: TurbineSpec, curve: TurbineCurve) -> float:
        return spec.rated_kw if spec.rated_kw is not None else curve.rated_kw

    def _pick(self, ids: list[str], spec: TurbineSpec) -> tuple[str, bool]:
        """Among equal candidates: nearest rating, measured curve, then id."""

        def key(curve_id: str):
            curve = self.curves[curve_id]
            gap = (abs(math.log(spec.rated_kw / curve.rated_kw))
                   if spec.rated_kw else 0.0)
            return (round(gap, 9), curve.curve_source != "oedb", curve_id)

        ranked = sorted(ids, key=key)
        ambiguous = len(ranked) > 1 and key(ranked[0])[:2] == \
            key(ranked[1])[:2]
        return ranked[0], ambiguous

    def _match_exact(self, spec: TurbineSpec, canon: str | None
                     ) -> TurbineMatch | None:
        words = self._manufacturer_words(canon)
        keys = [compact(spec.model)]
        stripped = spec.model.lower()
        for word in sorted(words, key=len, reverse=True):
            stripped = re.sub(rf"\b{re.escape(word)}\b", " ", stripped)
        keys.append(compact(stripped))
        if spec.manufacturer:
            keys.append(compact(f"{spec.manufacturer} {spec.model}"))
        ids: list[str] = []
        for key in keys:
            for curve_id in self._exact.get(key, ()):
                if curve_id not in ids and self._compatible(canon, curve_id):
                    ids.append(curve_id)
        if not ids:
            return None
        if spec.rated_kw is not None:
            close = [i for i in ids if abs(spec.rated_kw / self.curves[i]
                                           .rated_kw - 1.0)
                     <= FUZZY_CAPACITY_TOLERANCE]
            ids = close or ids
        curve_id, ambiguous = self._pick(ids, spec)
        curve = self.curves[curve_id]
        reason = f"model {spec.model!r} is a name of {curve_id}"
        if ambiguous:
            reason += " (one of several equal candidates; nearest rating)"
        return TurbineMatch("exact", curve, 1.0, reason,
                            self._rated(spec, curve))

    def _match_fuzzy(self, spec: TurbineSpec, canon: str | None
                     ) -> TurbineMatch | None:
        words = self._manufacturer_words(canon)
        parsed = parse_model(spec.model, words)
        wanted_kw = parsed.rated_kw
        inferred = False
        if wanted_kw is None and spec.rated_kw is not None:
            wanted_kw, inferred = spec.rated_kw, True
        if parsed.rotor_m is not None:
            ids = []
            for curve_id, key in self._keys.items():
                if not self._compatible(canon, curve_id):
                    continue
                if key.rotor_m is None:
                    key = ModelKey(key.prefix,
                                   self.curves[curve_id].rotor_diameter_m,
                                   key.rated_kw)
                if abs(key.rotor_m - parsed.rotor_m) > \
                        FUZZY_ROTOR_TOLERANCE_M:
                    continue
                if parsed.prefix and key.prefix and \
                        not _prefix_compatible(parsed.prefix, key.prefix):
                    continue
                rated = self.curves[curve_id].rated_kw
                if wanted_kw is not None:
                    tolerance = (FUZZY_CAPACITY_TOLERANCE if inferred
                                 else FUZZY_POWER_TOLERANCE)
                    if abs(wanted_kw / rated - 1.0) > tolerance:
                        continue
                ids.append(curve_id)
            if ids:
                probe = TurbineSpec(rated_kw=wanted_kw)
                curve_id, ambiguous = self._pick(ids, probe)
                curve = self.curves[curve_id]
                score = 1.0 if (parsed.rated_kw is not None) else 0.9
                if ambiguous or wanted_kw is None:
                    score = 0.8
                reason = (f"model {spec.model!r} parses to rotor "
                          f"{parsed.rotor_m:g} m"
                          + (f", {parsed.rated_kw:g} kW"
                             if parsed.rated_kw is not None else
                             (f", rating {spec.rated_kw:g} kW from the asset"
                              if inferred else ", no rating"))
                          + f"; {curve_id}")
                if ambiguous or wanted_kw is None:
                    reason += " (ambiguous; nearest rating, measured curve, " \
                              "then id)"
                return TurbineMatch("fuzzy", curve, score, reason,
                                    self._rated(spec, curve))
        if canon is None:
            return None
        target = compact(spec.model)
        best: tuple[float, str] | None = None
        for curve_id, curve in sorted(self.curves.items()):
            if self._canon.get(curve_id) != canon:
                continue
            for name in (curve.model,) + curve.names:
                ratio = difflib.SequenceMatcher(
                    None, target, compact(name)).ratio()
                if best is None or ratio > best[0] + 1e-12:
                    best = (ratio, curve_id)
        if best is None or best[0] < FUZZY_MIN_SIMILARITY:
            return None
        curve = self.curves[best[1]]
        if spec.rated_kw is not None and abs(spec.rated_kw / curve.rated_kw
                                             - 1.0) > SIZE_POWER_TOLERANCE:
            return None
        return TurbineMatch(
            "fuzzy", curve, best[0],
            f"model {spec.model!r} resembles {best[1]} "
            f"(similarity {best[0]:.2f})", self._rated(spec, curve))

    def _match_size(self, spec: TurbineSpec) -> TurbineMatch | None:
        best: tuple[float, str] | None = None
        for curve_id, curve in sorted(self.curves.items()):
            dp = math.log(spec.rated_kw / curve.rated_kw)
            dd = (spec.rotor_diameter_m - curve.rotor_diameter_m) \
                / curve.rotor_diameter_m
            if abs(math.exp(dp) - 1.0) > SIZE_POWER_TOLERANCE or \
                    abs(dd) > SIZE_ROTOR_TOLERANCE:
                continue
            distance = math.hypot(dp / SIZE_POWER_SCALE,
                                  dd / SIZE_ROTOR_SCALE)
            if spec.iec_class and curve.iec_class and \
                    spec.iec_class != curve.iec_class:
                distance += SIZE_CLASS_PENALTY
            if spec.offshore is not None and curve.offshore is not None and \
                    spec.offshore != curve.offshore:
                distance += SIZE_OFFSHORE_PENALTY
            if curve.curve_source != "oedb":
                distance += SIZE_PARAMETRIC_PENALTY
            if best is None or distance < best[0] - 1e-12:
                best = (distance, curve_id)
        if best is None:
            return None
        curve = self.curves[best[1]]
        return TurbineMatch(
            "size", curve, 1.0 / (1.0 + best[0]),
            f"{spec.rated_kw:g} kW, rotor {spec.rotor_diameter_m:g} m is "
            f"nearest {best[1]} ({curve.rated_kw:g} kW, "
            f"{curve.rotor_diameter_m:g} m; distance {best[0]:.2f})",
            spec.rated_kw)

    def generic_key(self, spec: TurbineSpec) -> str:
        if spec.offshore:
            return self.generic_default["offshore"]
        if spec.iec_class and f"iec_{spec.iec_class}" in self.generic:
            return f"iec_{spec.iec_class}"
        return self.generic_default["onshore"]

    def _match_generic(self, spec: TurbineSpec) -> TurbineMatch:
        if spec.rated_kw is None:
            return TurbineMatch(
                "none", None, 0.0,
                "no model match and no rated power on the asset or its "
                "forecast site", None)
        if spec.rotor_diameter_m is not None:
            sp = specific_power(spec.rated_kw / 1000.0,
                                spec.rotor_diameter_m)
            curve = generic_curve(
                spec.rated_kw, rotor_m=spec.rotor_diameter_m,
                label=f"parametric_sp{sp:.0f}", iec_class=spec.iec_class,
                offshore=spec.offshore)
            return TurbineMatch(
                "generic", curve, 0.0,
                f"no library curve within tolerance; parametric curve at "
                f"the asset's specific power {sp:.0f} W/m2", spec.rated_kw)
        key = self.generic_key(spec)
        entry = self.generic[key]
        curve = generic_curve(
            spec.rated_kw, sp_w_m2=float(entry["specific_power_w_m2"]),
            label=f"generic_{key}", iec_class=entry.get("iec_class"),
            offshore=entry.get("offshore"),
            cut_out_ms=float(entry.get("cut_out_ms",
                                       PARAMETRIC_CUT_OUT_MS)))
        return TurbineMatch(
            "generic", curve, 0.0,
            f"no rotor diameter; generic {key} curve "
            f"({entry['specific_power_w_m2']:g} W/m2) scaled to "
            f"{spec.rated_kw:g} kW", spec.rated_kw)


def _prefix_compatible(a: str, b: str) -> bool:
    synonyms = ({"vs", "vensys"}, {"swt", "sw"}, {"ge", "gewind"})
    if a == b:
        return True
    return any(a in group and b in group for group in synonyms)


def _optional_number(entry: Mapping[str, Any], key: str, what: str
                     ) -> float | None:
    value = entry.get(key)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, (int, float)) or \
            not math.isfinite(value) or value <= 0:
        raise TurbineLibraryRefused(f"{what}: {key} must be a positive "
                                    f"number or null, got {value!r}")
    return float(value)


def _curve_from_entry(entry: Any, path: Path) -> TurbineCurve:
    if not isinstance(entry, Mapping):
        raise TurbineLibraryRefused(f"turbine library {path}: an entry is "
                                    "not an object")
    ident = entry.get("id")
    what = f"turbine library {path} entry {ident!r}"
    if not isinstance(ident, str) or not ident:
        raise TurbineLibraryRefused(f"{what}: id must be a non-empty string")
    try:
        speeds = np.asarray(entry["wind_speed_ms"], dtype=float)
        power = np.asarray(entry["power_kw"], dtype=float)
        rated = float(entry["rated_kw"])
        rotor = float(entry["rotor_diameter_m"])
    except (KeyError, TypeError, ValueError) as error:
        raise TurbineLibraryRefused(f"{what} is malformed: {error}") \
            from error
    if speeds.ndim != 1 or speeds.shape != power.shape or speeds.size < 2:
        raise TurbineLibraryRefused(f"{what}: curve arrays differ or are short")
    if not (np.all(np.isfinite(speeds)) and np.all(np.isfinite(power))
            and math.isfinite(rated) and math.isfinite(rotor)):
        raise TurbineLibraryRefused(f"{what}: non-finite values")
    if np.any(np.diff(speeds) <= 0) or speeds[0] < 0:
        raise TurbineLibraryRefused(f"{what}: speeds must increase from >= 0")
    if np.any(power < 0) or power.max() > rated * 1.0001 or rated <= 0 \
            or rotor <= 0 or not np.any(power > 0):
        raise TurbineLibraryRefused(
            f"{what}: power must lie in [0, rated_kw], not all zero, with "
            "positive rating and rotor")
    source = entry.get("curve_source")
    if source not in ("oedb", "parametric"):
        raise TurbineLibraryRefused(f"{what}: curve_source {source!r}")
    iec = entry.get("iec_class")
    if iec is not None and iec not in IEC_CLASSES:
        raise TurbineLibraryRefused(f"{what}: iec_class {iec!r}")
    offshore = entry.get("offshore")
    if offshore is not None and not isinstance(offshore, bool):
        raise TurbineLibraryRefused(f"{what}: offshore must be true, false "
                                    "or null")
    names = entry.get("names") or []
    hubs = entry.get("hub_heights_m") or []
    if not isinstance(names, list) or not all(isinstance(n, str)
                                              for n in names):
        raise TurbineLibraryRefused(f"{what}: names must be strings")
    if not isinstance(hubs, list) or not all(
            isinstance(h, (int, float)) and not isinstance(h, bool)
            and h > 0 for h in hubs):
        raise TurbineLibraryRefused(f"{what}: hub_heights_m must be "
                                    "positive numbers")
    cut_out = _optional_number(entry, "cut_out_ms", what)
    if cut_out is None:
        cut_out = float(speeds[power > 0][-1])
    restart = _optional_number(entry, "restart_ms", what)
    gust = _optional_number(entry, "gust_cut_out_ms", what)
    if restart is not None and restart > cut_out:
        raise TurbineLibraryRefused(f"{what}: restart_ms above cut_out_ms")
    for key in ("manufacturer", "model", "source_url"):
        if entry.get(key) is not None and not isinstance(entry[key], str):
            raise TurbineLibraryRefused(f"{what}: {key} must be a string")
    return TurbineCurve(
        curve_id=ident, manufacturer=entry.get("manufacturer"),
        model=entry.get("model") or ident, rated_kw=rated,
        rotor_diameter_m=rotor, speeds=speeds, power_kw=power,
        curve_source=source, names=tuple(names), iec_class=iec,
        offshore=offshore, hub_heights_m=tuple(float(h) for h in hubs),
        cut_out_ms=cut_out, restart_ms=restart, gust_cut_out_ms=gust,
        source_url=entry.get("source_url"))


@functools.lru_cache(maxsize=4)
def _load_cached(path: str, mtime_ns: int) -> TurbineLibrary:
    del mtime_ns
    resolved = Path(path)
    try:
        document = json.loads(resolved.read_text())
    except (OSError, json.JSONDecodeError) as error:
        raise TurbineLibraryRefused(
            f"turbine library {resolved} cannot be read: {error}") from error
    if not isinstance(document, dict) or \
            document.get("schema") != TURBINE_LIBRARY_SCHEMA:
        raise TurbineLibraryRefused(
            f"turbine library {resolved} is not a {TURBINE_LIBRARY_SCHEMA} "
            "document")
    for key in ("license", "attribution", "turbines", "generic",
                "manufacturer_aliases"):
        if key not in document:
            raise TurbineLibraryRefused(
                f"turbine library {resolved} lacks {key!r}")
    curves: dict[str, TurbineCurve] = {}
    if not isinstance(document["turbines"], list) or \
            not isinstance(document["generic"], dict) or \
            not isinstance(document["manufacturer_aliases"], dict):
        raise TurbineLibraryRefused(
            f"turbine library {resolved}: turbines must be a list, generic "
            "and manufacturer_aliases objects")
    for entry in document["turbines"]:
        curve = _curve_from_entry(entry, resolved)
        if curve.curve_id in curves:
            raise TurbineLibraryRefused(
                f"turbine library {resolved}: duplicate id {curve.curve_id!r}")
        curves[curve.curve_id] = curve
    generic = dict(document["generic"])
    default = dict(document.get("generic_default") or {})
    for need in ("onshore", "offshore"):
        if default.get(need) not in generic:
            raise TurbineLibraryRefused(
                f"turbine library {resolved}: generic_default.{need} must "
                "name a generic curve")
    for key, entry in generic.items():
        if not isinstance(entry, dict):
            raise TurbineLibraryRefused(
                f"turbine library {resolved}: generic {key!r} is not an "
                "object")
        sp = entry.get("specific_power_w_m2")
        if not isinstance(sp, (int, float)) or not 50 <= sp <= 1000:
            raise TurbineLibraryRefused(
                f"turbine library {resolved}: generic {key!r} needs a "
                "specific_power_w_m2 in [50, 1000]")
    aliases = {str(k): str(v) for k, v in
               document["manufacturer_aliases"].items()}
    return TurbineLibrary(
        path=resolved, sha256=sha256_file(resolved),
        license=str(document["license"]),
        attribution=str(document["attribution"]), curves=curves,
        manufacturer_aliases=aliases, generic=generic,
        generic_default=default)


def load_turbine_library(path: str | Path | None = None) -> TurbineLibrary:
    """Read and validate a ``woof-energy.turbine-library.v1`` document."""

    resolved = Path(path) if path is not None else DEFAULT_TURBINE_LIBRARY
    if not resolved.is_file():
        raise TurbineLibraryRefused(f"turbine library {resolved} does not "
                                    "exist")
    resolved = resolved.resolve()
    return _load_cached(str(resolved), resolved.stat().st_mtime_ns)


