# normalisation


def compact(text: str | None) -> str:
    """Lower-case alphanumerics, with a trailing ``mw``/``kw`` unit dropped."""

    if not text:
        return ""
    out = re.sub(r"[^0-9a-z]", "", str(text).lower())
    return re.sub(r"(mw|kw)$", "", out)


def canonical_manufacturer(text: str | None,
                           aliases: Mapping[str, str]) -> str | None:
    """Canonical manufacturer name via the alias table (``None`` if blank)."""

    if not text or not str(text).strip():
        return None
    key = re.sub(r"[^0-9a-z]+", " ", str(text).lower()).strip()
    if key in aliases:
        return aliases[key]
    # Longest alias that starts the name ("vestas wind systems a s").
    for alias in sorted(aliases, key=lambda a: (-len(a), a)):
        if key.startswith(alias + " "):
            return aliases[alias]
    return key.replace(" ", "-")


@dataclass(frozen=True)
class ModelKey:
    """What a model string says: family prefix, rotor diameter, rating."""

    prefix: str
    rotor_m: float | None
    rated_kw: float | None


_NUMBER = re.compile(r"(\d+(?:[.,]\d+)?)\s*(mw|kw)?", re.IGNORECASE)


def parse_model(text: str | None, manufacturer_words: Iterable[str] = ()
                ) -> ModelKey:
    """Parse ``V112-3.0 MW``, ``SWT-3.6-107``, ``E-101/3050``, ``GE1.5-77``.

    A number with a decimal point of at most 20 (or any number followed by
    ``MW``) is a rating in MW; a number of 500-20000 (or followed by ``kW``)
    a rating in kW.  The leading number (right after the family letters)
    is a rotor diameter when it is 15-300, unless it is a whole number of at
    most 20 followed later by a rotor-sized number ("SG 14-222": 14 MW).
    Otherwise a number of 30-300 is the rotor diameter, and once the rotor
    is known a number of 30-499 is a rating in kW ("V27-225").  Other
    numbers ("E2", "EP4") are ignored.  The prefix is the leading letters once
    manufacturer words are removed.
    """

    if not text:
        return ModelKey("", None, None)
    low = str(text).lower()
    for word in sorted(manufacturer_words, key=len, reverse=True):
        if word:
            low = re.sub(rf"\b{re.escape(word)}\b", " ", low)
    low = low.strip(" -/_")
    prefix_match = re.match(r"\s*([a-z]+)", low)
    prefix = prefix_match.group(1) if prefix_match else ""
    rotor = rated = None
    numbers = [(m.group(1).replace(",", "."), (m.group(2) or "").lower(),
                m.start(1)) for m in _NUMBER.finditer(low)]
    later_rotor = [30.0 <= float(raw) <= 300.0 for raw, _, _ in numbers]
    for k, (raw, unit, start) in enumerate(numbers):
        value = float(raw)
        leading = k == 0 and re.fullmatch(r"\s*[a-z]*[\s\-/]*",
                                          low[:start]) is not None
        if unit == "mw" or ("." in raw and 0.0 < value <= 20.0):
            if rated is None and 0.0 < value <= 20.0:
                rated = value * 1000.0
        elif unit == "kw" or 500.0 <= value <= 20000.0:
            if rated is None and value > 0.0:
                rated = value
        elif leading and "." not in raw and value <= 20.0 and \
                any(later_rotor[k + 1:]):
            rated = value * 1000.0          # "SG 14-222": 14 MW
        elif leading and 15.0 <= value <= 300.0:
            rotor = value                   # "V27-225", "E-40", "MM92"
        elif 30.0 <= value <= 300.0 and rotor is None:
            rotor = value
        elif 30.0 <= value < 500.0 and rotor is not None and rated is None:
            rated = value                   # "V27-225": 225 kW
        # anything else ("E2", "EP4") says nothing
    return ModelKey(prefix, rotor, rated)


def parse_power_kw(text: Any, *, bare: str = "auto") -> float | None:
    """``"3 MW"``, ``"3000 kW"``, ``"3,000 kW"``, ``"3.0"`` (MW) -> kW.

    A number with no unit is kW with ``bare="kw"`` (USWTDB ``t_cap``); with
    ``bare="auto"`` it is MW when it has a fractional part and is below 30
    (``"2.3"``), otherwise kW (``"850"``, ``"25"``: small turbines).
    """

    if text is None:
        return None
    if isinstance(text, (int, float)):
        value = float(text)
        return value if math.isfinite(value) and value > 0 else None
    raw = str(text).strip().lower().replace(" ", "")
    match = re.match(r"^(\d+(?:[.,]\d+)*)(mw|kw|w)?$", raw)
    if not match:
        return None
    digits = match.group(1)
    if "," in digits and "." not in digits and re.fullmatch(
            r"\d{1,3}(,\d{3})+", digits):
        digits = digits.replace(",", "")
    else:
        digits = digits.replace(",", ".")
    try:
        value = float(digits)
    except ValueError:
        return None
    unit = match.group(2)
    if unit == "mw":
        value *= 1000.0
    elif unit == "w":
        value /= 1000.0
    elif unit is None and bare == "auto" and not value.is_integer() \
            and value < 30.0:
        value *= 1000.0
    return value if value > 0 else None


def parse_length_m(text: Any) -> float | None:
    if text is None:
        return None
    if isinstance(text, (int, float)):
        value = float(text)
    else:
        match = re.match(r"^\s*(\d+(?:\.\d+)?)\s*(m)?\s*$", str(text).lower())
        if not match:
            return None
        value = float(match.group(1))
    return value if math.isfinite(value) and value > 0 else None


def parse_iec_class(text: Any) -> str | None:
    """``IEC IIA/IEC S`` -> ``II``; ``IEC la`` (sic) -> ``I``; ``S``."""

    if not text:
        return None
    raw = str(text).strip()
    match = re.search(r"(?:IEC(?:/EN)?\s*)?\b([IlS]{1,3})(?:[ABCabc+]|\b)",
                      raw)
    if not match:
        return None
    token = match.group(1).replace("l", "I").upper()
    if token.startswith("S"):
        return "S"
    if token in ("I", "II", "III"):
        return token
    return None


def _truthy_offshore(key: str, value: str) -> bool | None:
    low = value.strip().lower()
    if key == "offshore" or key == "t_offshore":
        if low in ("yes", "true", "1"):
            return True
        if low in ("no", "false", "0"):
            return False
        return None
    if low == "offshore":
        return True
    if low == "onshore":
        return False
    return None


