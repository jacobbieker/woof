"""GEM-15: the pinned cell index and the coverage policy.

GEM-15 v1 (Google Research, 2026; experimental) publishes a 15 m surface
model (``dsm``) and bare-earth terrain model (``dtm``) as one
Cloud-Optimized BigTIFF per 1x1-degree cell, each in its own UTM zone, in
the public bucket ``gs://climate-and-sustainability/gem-15``.  The source
rows (licence, attribution, datum, the experimental warning) are
:data:`woof.static.highres_fetch.EXPERIMENTAL_TERRAIN_SOURCES`; this module
answers the two questions those rows cannot:

* WHICH OBJECT.  Cell URLs are read from a pinned snapshot of the
  producer's STAC catalog and GCS object listing
  (``woof/data/gem15_index.v1.json.gz``, regenerated by
  ``tools/gem15_index.py``), never built from a formula.  Each object is
  pinned by the size, CRC32C, MD5 (where GCS publishes one) and generation
  Google publishes; GCS publishes no SHA-256, so woof records one for every
  byte range on its first download and verifies it on every later read
  (:mod:`woof.static.highres_fetch` sidecars).
* WHERE IT MAY BE USED.  The producer excludes Russia, China, Mongolia,
  Greenland and Antarctica, and deliberately offsets India and a band
  tapering over tens of km outside its border.  A footprint touching any
  of those, or one where the snapshot lists no cell at all, takes
  Copernicus GLO-30 instead, with a warning and a receipt line
  (:func:`fallback_reason`).  Holes inside a published cell (water, snow,
  ice, low texture) stay holes and keep the 30-arc-second baseline, as
  unpublished GLO-30 tiles do.

The region outlines are Natural Earth 1:110m countries (public domain,
``woof/data/gem15_fallback_regions.v1.json``).  A footprint is tested
against them padded by each region's margin, so the coarse outline errs
toward GLO-30, never toward offset or missing GEM-15 heights.
"""
from __future__ import annotations

import base64
import functools
import gzip
import json
import math
from dataclasses import dataclass
from pathlib import Path

from .highres_fetch import (EXPERIMENTAL_TERRAIN_SOURCES, FootprintBBox,
                            GEM15_BUCKET_URL, GEM15_LAT_MAX, GEM15_LAT_MIN)

_DATA = Path(__file__).resolve().parent.parent / "data"
INDEX_PATH = _DATA / "gem15_index.v1.json.gz"
REGIONS_PATH = _DATA / "gem15_fallback_regions.v1.json"
INDEX_SCHEMA = "woof.gem15-index.v1"
REGIONS_SCHEMA = "woof.gem15-fallback-regions.v1"

#: Source id -> (bucket asset, samples per pixel, the band read).  The DSM
#: file interleaves five bands per pixel (dsm, its 5th/50th/95th
#: percentiles and std); terrain reads band 0, ``dsm``.
ASSETS: dict[str, tuple[str, int, int]] = {
    "gem15-dtm": ("dtm", 1, 0),
    "gem15-dsm": ("dsm", 5, 0),
}

#: Where a domain GEM-15 may not serve goes instead.
FALLBACK_SOURCE = "copernicus-dem-glo30"


def _hex(digest_b64: str | None) -> str | None:
    return None if digest_b64 is None else base64.b64decode(digest_b64).hex()


@dataclass(frozen=True)
class Gem15Object:
    """One published object, pinned by Google's own GCS metadata."""

    url: str
    bytes: int
    md5_base64: str | None
    crc32c_base64: str
    generation: str
    shape: tuple[int, int]
    transform: tuple[float, ...]

    @property
    def md5(self) -> str | None:
        """Hex MD5 of the whole object; None for a GCS composite."""
        return _hex(self.md5_base64)

    @property
    def crc32c(self) -> str:
        return _hex(self.crc32c_base64)

    def echo(self) -> dict[str, object]:
        return {"url": self.url, "bytes": self.bytes, "md5": self.md5,
                "crc32c": self.crc32c, "generation": self.generation}


@dataclass(frozen=True)
class Gem15Cell:
    """One 1x1-degree cell of the pinned snapshot."""

    cell_id: str
    group: str
    lat_sw: int
    lon_sw: int
    epsg: int
    objects: dict

    def object(self, source_id: str) -> Gem15Object:
        asset = ASSETS[source_id][0]
        return self.objects[asset]

    @property
    def bbox(self) -> FootprintBBox:
        return FootprintBBox(self.lat_sw, self.lat_sw + 1.0,
                             self.lon_sw, self.lon_sw + 1.0)


@dataclass(frozen=True)
class Gem15Index:
    snapshot_utc: str
    bucket_url: str
    cells: dict

    def cell(self, lat_sw: int, lon_sw: int) -> Gem15Cell | None:
        return self.cells.get((int(lat_sw), int(lon_sw)))

    def cells_over(self, bbox: FootprintBBox
                   ) -> tuple[tuple[Gem15Cell, ...], tuple[tuple[int, int], ...]]:
        """``(published, unpublished)`` 1x1-degree squares over ``bbox``.

        ``unpublished`` names each square's south-west corner as
        ``(lat, lon)``.  A continued longitude range past 180 (a dateline
        footprint) is wrapped square by square, as the GLO-30 enumerator
        does.
        """
        published, unpublished = [], []
        lat_lo = max(-90, int(math.floor(bbox.lat_min)))
        lat_hi = min(90, int(math.ceil(bbox.lat_max)))
        for lat in range(lat_lo, lat_hi):
            for lon in range(int(math.floor(bbox.lon_min)),
                             int(math.ceil(bbox.lon_max))):
                wrapped = ((lon + 180) % 360) - 180
                hit = self.cell(lat, wrapped)
                (published.append(hit) if hit is not None
                 else unpublished.append((lat, wrapped)))
        return tuple(published), tuple(unpublished)


@functools.lru_cache(maxsize=1)
def load_index(path: Path = INDEX_PATH) -> Gem15Index:
    """The pinned snapshot, parsed once."""
    payload = json.loads(gzip.decompress(Path(path).read_bytes()))
    if payload.get("schema") != INDEX_SCHEMA:
        raise ValueError(f"{path}: schema {payload.get('schema')!r} is not "
                         f"{INDEX_SCHEMA!r}")
    base = payload["bucket_url"]
    if base != GEM15_BUCKET_URL:
        raise ValueError(f"{path}: bucket {base!r} is not {GEM15_BUCKET_URL!r}")
    cells = {}
    for cell_id, row in payload["cells"].items():
        objects = {}
        for asset in ("dtm", "dsm"):
            size, md5, crc, generation, shape, transform = row[asset]
            objects[asset] = Gem15Object(
                url=f"{base}/{row['group']}/{cell_id}/{asset}/zall/mosaic.tif",
                bytes=int(size), md5_base64=md5, crc32c_base64=crc,
                generation=str(generation),
                shape=(int(shape[0]), int(shape[1])),
                transform=tuple(float(v) for v in transform))
        lat_sw, lon_sw = (int(v) for v in row["sw"])
        cells[(lat_sw, lon_sw)] = Gem15Cell(
            cell_id=cell_id, group=row["group"], lat_sw=lat_sw,
            lon_sw=lon_sw, epsg=int(row["epsg"]), objects=objects)
    return Gem15Index(snapshot_utc=payload["snapshot_utc"], bucket_url=base,
                      cells=cells)


@functools.lru_cache(maxsize=1)
def load_regions(path: Path = REGIONS_PATH) -> dict:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    if payload.get("schema") != REGIONS_SCHEMA:
        raise ValueError(f"{path}: schema {payload.get('schema')!r} is not "
                         f"{REGIONS_SCHEMA!r}")
    return payload["regions"]


def _inside(x: float, y: float, ring) -> bool:
    """Even-odd point-in-ring."""
    inside = False
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        if (y1 > y) != (y2 > y):
            if x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                inside = not inside
    return inside


def _segment_hits_box(x1, y1, x2, y2, west, south, east, north) -> bool:
    """Liang-Barsky: does the segment meet the closed box?"""
    t0, t1 = 0.0, 1.0
    dx, dy = x2 - x1, y2 - y1
    for p, q in ((-dx, x1 - west), (dx, east - x1),
                 (-dy, y1 - south), (dy, north - y1)):
        if p == 0.0:
            if q < 0.0:
                return False
            continue
        t = q / p
        if p < 0.0:
            t0 = max(t0, t)
        else:
            t1 = min(t1, t)
        if t0 > t1:
            return False
    return True


def _box_meets_ring(box, ring) -> bool:
    west, south, east, north = box
    if any(_inside(x, y, ring) for x, y in
           ((west, south), (east, south), (east, north), (west, north))):
        return True
    n = len(ring)
    return any(_segment_hits_box(*ring[i], *ring[(i + 1) % n], *box)
               for i in range(n))


def regions_touched(bbox: FootprintBBox) -> tuple[tuple[str, str, str], ...]:
    """``(code, name, why)`` of each fallback region the footprint,
    padded by that region's margin, touches."""
    hits = []
    for code, region in sorted(load_regions().items()):
        pad = float(region["margin_deg"])
        boxes = []
        for shift in (0.0, -360.0, 360.0):
            west, east = bbox.lon_min + shift - pad, bbox.lon_max + shift + pad
            if east < -180.0 - pad or west > 180.0 + pad:
                continue
            boxes.append((west, bbox.lat_min - pad, east, bbox.lat_max + pad))
        if any(_box_meets_ring(box, ring) for box in boxes
               for ring in region["rings"]):
            hits.append((code, region["name"], region["why"]))
    return tuple(hits)


def fallback_reason(bbox: FootprintBBox, source_id: str) -> str | None:
    """Why a GEM-15 selection must take :data:`FALLBACK_SOURCE` over
    ``bbox`` instead, or None when GEM-15 may serve it.

    In order: the footprint leaves 61 S .. 84 N; it touches an excluded
    country or India's offset band (padded outlines, see the module
    docstring); the snapshot lists no cell over it at all.
    """
    if source_id not in ASSETS:
        raise KeyError(f"{source_id!r} is not a GEM-15 source; known "
                       f"{sorted(ASSETS)}")
    if bbox.lat_min < GEM15_LAT_MIN or bbox.lat_max > GEM15_LAT_MAX:
        return (f"the footprint {bbox.as_dict()} leaves GEM-15's published "
                f"latitudes {GEM15_LAT_MIN:g}..{GEM15_LAT_MAX:g}")
    touched = regions_touched(bbox)
    if touched:
        named = "; ".join(f"{name} ({why})" for _, name, why in touched)
        return (f"the footprint {bbox.as_dict()} touches a region GEM-15 "
                f"does not serve: {named}")
    published, _ = load_index().cells_over(bbox)
    if not published:
        return (f"the pinned GEM-15 snapshot ({load_index().snapshot_utc}) "
                f"lists no cell over the footprint {bbox.as_dict()}")
    return None


def source_row(source_id: str):
    """The registry row of one GEM-15 source id."""
    return EXPERIMENTAL_TERRAIN_SOURCES[source_id]


