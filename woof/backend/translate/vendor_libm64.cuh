            if (x == -1.0f) return __int_as_float(0xff800000U);
            if (ax > 0x7f800000) return __fadd_rn(x, x);
            return __int_as_float(0xffc00000U);
        }
        if (ax < 0x31000000) return x;
        if (hx > 0 || hx <= (int)0xbe95f61fU) { k = 0; f = x; hu = 1; }
    } else if (hx >= 0x7f800000) return __fadd_rn(x, x);
