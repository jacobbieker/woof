            c = k > 0 ? __fsub_rn(1.0f, __fsub_rn(u, x)) : __fsub_rn(x, __fsub_rn(u, 1.0f)); c = __fdiv_rn(c, u);
        } else { u = x; hu = __float_as_int(u); k = (hu >> 23) - 127; }
        hu &= 0x007fffff;
