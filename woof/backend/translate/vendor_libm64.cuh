// cbrtf.rs (Rust libm 0.2.16).
__device__ __forceinline__ float wlm_cbrtf(float x) {
    unsigned ui = __float_as_uint(x), hx = ui & 0x7fffffffu;
    if (hx >= 0x7f800000u) return __fadd_rn(x, x);
    if (hx < 0x00800000u) {
        if (hx == 0u) return x;
        ui = __float_as_uint(__fmul_rn(x, 16777216.0f));
        hx = ui & 0x7fffffffu;
        hx = hx / 3u + 642849266u;
    } else {
        hx = hx / 3u + 709958130u;
    }
    ui &= 0x80000000u;
    ui |= hx;
    double t = (double)__uint_as_float(ui), xd = (double)x;
    double r = __dmul_rn(__dmul_rn(t, t), t);
    t = __ddiv_rn(__dmul_rn(t, __dadd_rn(__dadd_rn(xd, xd), r)), __dadd_rn(__dadd_rn(xd, r), r));
    r = __dmul_rn(__dmul_rn(t, t), t);
    t = __ddiv_rn(__dmul_rn(t, __dadd_rn(__dadd_rn(xd, xd), r)), __dadd_rn(__dadd_rn(xd, r), r));
    return __double2float_rn(t);
}
