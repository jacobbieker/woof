        }
        float r = __fmul_rn(hfsq, __fsub_rn(1.0f, __fmul_rn(__int_as_float(0x3f2aaaab), f)));
        if (k == 0) return __fsub_rn(f, r);
        return __fsub_rn(__fmul_rn(kf, wlm_LN2_HI), __fsub_rn(__fsub_rn(r, __fadd_rn(__fmul_rn(kf, wlm_LN2_LO), c)), f));
    }
