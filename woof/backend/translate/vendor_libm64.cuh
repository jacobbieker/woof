    float s = __fdiv_rn(f, __fadd_rn(2.0f, f)), z = __fmul_rn(s, s);
    float r = __fmul_rn(z, __fadd_rn(wlm_LP1, __fmul_rn(z, __fadd_rn(wlm_LP2, __fmul_rn(z, __fadd_rn(wlm_LP3, __fmul_rn(z, __fadd_rn(wlm_LP4, __fmul_rn(z, __fadd_rn(wlm_LP5, __fmul_rn(z, __fadd_rn(wlm_LP6, __fmul_rn(z, wlm_LP7)))))))))))));
    if (k == 0) return __fsub_rn(f, __fsub_rn(hfsq, __fmul_rn(s, __fadd_rn(hfsq, r))));
    return __fsub_rn(__fmul_rn(kf, wlm_LN2_HI), __fsub_rn(__fsub_rn(hfsq, __fadd_rn(__fmul_rn(s, __fadd_rn(hfsq, r)), __fadd_rn(__fmul_rn(kf, wlm_LN2_LO), c))), f));
