__device__ __forceinline__ double wlm_lgamma_sin_pi(double x) {
    const double wlm_PI = wlm_bits(0x400921fb54442d18);
    x = __dmul_rn(2.0, __dsub_rn(__dmul_rn(x, 0.5), floor(__dmul_rn(x, 0.5))));
    int n = wlm_i32(__dmul_rn(x, 4.0));
    n = (n + 1) / 2;
    x = __dsub_rn(x, __dmul_rn(__int2double_rn(n), 0.5));
    x = __dmul_rn(x, wlm_PI);
    if (n == 1) return wlm_k_cos(x, 0.0);
    if (n == 2) return wlm_k_sin(wlm_negd(x), 0.0, 0);
    if (n == 3) return wlm_negd(wlm_k_cos(x, 0.0));
    return wlm_k_sin(x, 0.0, 0);
}
