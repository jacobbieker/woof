__device__ __forceinline__ float wlm_log1pf(float x) {
    int hx = __float_as_int(x), ax = hx & 0x7fffffff, k = 1, hu = 0;
    // wlm_CUDA float addition canonicalizes NaNs. The host x+x quiets the
    // input payload and retains its sign, so perform that bit operation.
    if (ax > 0x7f800000) return __int_as_float(hx | 0x00400000);
    float f = 0.0f, c = 0.0f;
    const float wlm_LN2_HI = __int_as_float(0x3f317180), wlm_LN2_LO = __int_as_float(0x3717f7d1);
