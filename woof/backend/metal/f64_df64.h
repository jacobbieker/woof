// Double-float ("df64") binary64 for the MLX backend's fast numerics.
//
// Apple GPUs have no binary64.  Strict numerics (GPUWM_WRF_EXACT=1) computes
// every `double` with f64_soft.h, word for word, except division and square
// root, which are this header's exact df64-seeded words (the same words,
// faster; the libm below is left out).  Fast numerics (the default)
// keeps the same storage -- `double` is still the binary64 word `f64`, so
// every buffer, struct, literal, union and bit cast is unchanged -- but takes
// the expensive parts through df64, an unevaluated pair (hi, lo) of binary32
// values with |lo| <= ulp(hi)/2 and about 48 significant bits:
//
// * division and square root: a df64 estimate, then an exact integer
//   remainder and at most a few unit steps, so the result is the correctly
//   rounded binary64 word (the soft-float digit loops are 63 iterations);
// * exp, log, log2, log10, log1p, expm1, pow, sin, cos, tan, atan, atan2,
//   tanh, hypot, cbrt: computed in df64 from the binary64 word, the exponent
//   carried apart in an integer, so the whole binary64 range is covered and
//   nothing overflows or flushes in binary32.  Accuracy is stated per
//   function below and graded by tools/df64_grade.py.
//
// Addition, subtraction, multiplication, fma, conversions and comparisons
// stay f64_soft.h's exact integer operations (tools/df64_grade.py's bench
// measured them no slower than a df64 round trip through the binary64
// word, and exact subtraction keeps Sterbenz cancellation exact).  The df64
// versions are here too (df_add, df_mul, ...), graded against binary64, and
// the libm is built on them.
//
// This text follows f64_soft.h (it uses its typedefs, f64_round_pack, and
// the soft operations as exact fallbacks) and, like it, compiles both as
// Metal Shading Language and as host C++17, so tools/df64_grade.py grades
// the same text on the CPU.  Every df64 function here assumes binary32
// arithmetic without contraction (the prelude's `fp contract(off)`; the host
// grader builds with -ffp-contract=off) and IEEE + - * / fma sqrt (Metal's
// math_mode safe, woof/backend/metal/arith_receipt.json).
#pragma once

