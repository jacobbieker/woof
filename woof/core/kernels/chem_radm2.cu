// setdtc's per-level candidate: the smallest .02*vc/|prod-loss| over the
// species with qdtc = 1, or huge (module_radm.F:1662-1684).
__device__ float r2_level_dtlsp(const float *prod, const float *loss, const float *vc) {
    const float huge = 1.e10f;
    float best = huge;
    for (int l = 0; l < R2_LPRED; ++l) {
        if (R2_QDTC[l] != 1) continue;
        float dum = FSUB(prod[l], loss[l]);
        dum = fmaxf(fabsf(dum), 1.e-30f);
        dum = FDIV(FMUL(0.02f, vc[l]), dum);
        if (!(FSUB(vc[l], 1.e-10f) >= 0.f)) dum = huge;
        best = fminf(best, dum);
    }
    return best;
}

