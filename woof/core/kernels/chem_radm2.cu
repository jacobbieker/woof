// nclamp further rows that radm_driver only floors at epsilc (module_radm.F:98).
// ph: the 21 photolysis fields in radm_driver's rj order (module_radm.F:190-212).
// vdrog: R2_LDROG fields or 0; written for the 11 RADM2 precursors only.
