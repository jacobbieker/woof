    const unsigned long long* rows, int nclamp,
    const float* t_phy, const float* p_phy, const float* qv,
    const unsigned long long* ph, const unsigned long long* vdrog3,
    int nz, int nc, float dt60, float dtcmin, float dtcmax) {
