// WOOF's own solver for SORGAM's absorptive gas/particle partitioning, the
// default build's replacement for module_aerosols_sorgam.F's newt/lnsrch/
// fmin/ludcmp/lubksb, which are derived from Numerical Recipes (whose licence
// forbids redistributing them).  Written from the problem, not from that code:
//
//   F_i(x) = 0, i = 1..n, x_i the particle-phase mass of condensable vapour i
//   (Schell, Ackermann, Hass, Binkowski and Ebel 2001, J. Geophys. Res. 106,
//   28275, eq. 9: x_i = ctot_i - csat_i * (x_i / mw_i) / (sum_j x_j / mw_j + M)),
//   cleared of its denominator; F and its Jacobian J are SORGAM's own funcv and
//   fdjac (generated above).
//
// Method: Newton's method with a backtracking (Armijo) line search on the
// merit function phi = |F|^2 / 2 (Dennis and Schnabel 1996, "Numerical Methods
// for Unconstrained Optimization and Nonlinear Equations", sections 6.3 and
// 6.5), each trial point kept inside the physical box [SG_CONMIN, ctot_i]; the
// Newton step solves J s = -F by Gaussian elimination with partial pivoting.
// Stops when the accepted step moves every x_i by less than R_TOL relative, or
// F is exactly zero (F's scale follows the concentrations, so no absolute
// threshold on it is meaningful); check reports a singular J, a line search that could
// not reduce phi, or R_MAXIT iterations without convergence.  Graded against
// WRF's own solver (the exact path) within a stated tolerance, not bitwise
// (tests/test_chem_sorgam_wrf461_parity.py).
#define R_MAXIT 100
#define R_MAXHALF 40
#define R_TOL 1.0e-6f
#define R_ARMIJO 1.0e-4f

__device__ float sg_cr_merit(const float *f, int n) {
    float s = 0.f;
    for (int i = 0; i < n; ++i) s = FADD(s, FMUL(f[i], f[i]));
    return FMUL(0.5f, s);
}

// Solve J s = r (J column-major n x n, overwritten); false if J is singular.
__device__ bool sg_cr_gauss(float *J, float *r, int n) {
    for (int c = 0; c < n; ++c) {
        int piv = c;
        float big = fabsf(J[c + n * c]);
        for (int q = c + 1; q < n; ++q) {
            float v = fabsf(J[q + n * c]);
            if (v > big) { big = v; piv = q; }
        }
        if (!(big > 0.f)) return false;
        if (piv != c) {
            for (int k = 0; k < n; ++k) {
                float t = J[c + n * k]; J[c + n * k] = J[piv + n * k]; J[piv + n * k] = t;
            }
            float t = r[c]; r[c] = r[piv]; r[piv] = t;
        }
        for (int q = c + 1; q < n; ++q) {
            float w = FDIV(J[q + n * c], J[c + n * c]);
            if (w == 0.f) continue;
            for (int k = c + 1; k < n; ++k) J[q + n * k] = FSUB(J[q + n * k], FMUL(w, J[c + n * k]));
            r[q] = FSUB(r[q], FMUL(w, r[c]));
        }
    }
    for (int c = n - 1; c >= 0; --c) {
        float acc = r[c];
        for (int k = c + 1; k < n; ++k) acc = FSUB(acc, FMUL(J[c + n * k], r[k]));
        r[c] = FDIV(acc, J[c + n * c]);
    }
    return true;
}

__device__ void sg_newt(SorgamModule &mod, int layer, float *x, int n, bool &check,
                        const float *ctot, const float *csat, const float *imwcv,
                        float minitw, int &its) {
    float f[SG_NP], J[SG_NP * SG_NP], step[SG_NP], trial[SG_NP], ft[SG_NP];
    (void)layer;
    check = false;
    sg_funcv(mod, n, x, f, ctot, csat, imwcv, minitw);
    float phi = sg_cr_merit(f, n);
    for (its = 1; its <= R_MAXIT; ++its) {
        if (phi == 0.f) return;
        sg_fdjac(mod, n, x, J, ctot, csat, imwcv);
        for (int i = 0; i < n; ++i) step[i] = -f[i];
        if (!sg_cr_gauss(J, step, n)) { check = true; return; }
        // Backtrack along the Newton direction: for it, d(phi)/d(lambda) at
        // lambda = 0 is -2 phi, so Armijo asks phi(lambda) <= (1 - 2 c lambda) phi.
        float lambda = 1.f, phit = phi;
        bool accepted = false;
        for (int h = 0; h < R_MAXHALF; ++h) {
            for (int i = 0; i < n; ++i) {
                float v = FADD(x[i], FMUL(lambda, step[i]));
                trial[i] = f2cu_minf(f2cu_maxf(v, SG_CONMIN), ctot[i]);
            }
            sg_funcv(mod, n, trial, ft, ctot, csat, imwcv, minitw);
            phit = sg_cr_merit(ft, n);
            if (phit <= FMUL(FSUB(1.f, FMUL(FMUL(2.f, R_ARMIJO), lambda)), phi)) {
                accepted = true;
                break;
            }
            lambda = FMUL(0.5f, lambda);
        }
        if (!accepted) { check = true; return; }
        bool small = true;
        for (int i = 0; i < n; ++i) {
            float moved = fabsf(FSUB(trial[i], x[i]));
            if (moved > FMUL(R_TOL, f2cu_maxf(fabsf(x[i]), SG_CONMIN))) small = false;
            x[i] = trial[i];
            f[i] = ft[i];
        }
        phi = phit;
        if (small) return;
    }
    its = R_MAXIT;
    check = true;
}
