#!/usr/bin/env bash
# WOOF-OPTIN: wrfchem_pnnl
# Build and run the Abdul-Razzak and Ghan activation oracle against WRF v4.7.1.
#
#   bash optional/wrfchem_pnnl/oracle/activate/build.sh WRF_SRC BUILD_DIR [FIXTURE_ROOT]
#
# share/module_model_constants.F compiles whole and unchanged.  The routines in
# routines.list are copied BYTE FOR BYTE from YOUR tree's phys/module_mixactivate.F
# into one wrapper module, unchanged; nothing of that file is committed to WOOF
# (its PNNL terms, and erfc_num_recipes' Numerical Recipes origin).  stub_wrf.F90
# supplies wrf_error_fatal.  -O0, and the build fails if any -O0 object imports a
# libmvec _ZGV* symbol (positive control included).  ORACLE_COVERAGE=1 adds gcov.
set -euo pipefail
if [[ $# -lt 2 ]]; then
    echo "usage: build.sh WRF_SRC BUILD_DIR [FIXTURE_ROOT]" >&2
    exit 2
fi
src=$(realpath "$1")
build=$(realpath -m "$2")
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
fixtures=$(realpath -m "${3:-${build}/fixtures}")

while read -r sum rel; do
    [[ -z "${sum}" || "${sum}" == \#* ]] && continue
    got=$(sha256sum "${src}/${rel}" | cut -d' ' -f1)
    if [[ "${got}" != "${sum}" ]]; then
        echo "${rel}: sha256 ${got}, pinned ${sum}" >&2
        exit 3
    fi
done < "${here}/SOURCES.sha256"

mkdir -p "${build}" "${fixtures}"
cd "${build}"
defines="-DEM_CORE=1 -DNMM_CORE=0 -DRWORDSIZE=4 -DIWORDSIZE=4 -DDWORDSIZE=8 -DLWORDSIZE=4 -DWRF_CHEM=1"
free="-ffree-form -ffree-line-length-none -fallow-argument-mismatch"
fc="gfortran -c -O0 ${ORACLE_COVERAGE:+--coverage} -cpp ${defines} ${free} -I ${build}"

: > undefined-O0.txt
guard() {
    nm -u "$1" | sed 's/^ *//' | sort > "undefined-$1.txt"
    cat "undefined-$1.txt" >> undefined-O0.txt
    if grep -q '_ZGV' "undefined-$1.txt"; then
        echo "-O0 object $1 pulled in a libmvec vector symbol" >&2
        exit 4
    fi
}
${fc} "${here}/stub_wrf.F90"; guard stub_wrf.o
${fc} "${here}/oracle_io.F90"; guard oracle_io.o
${fc} -o module_model_constants.o "${src}/share/module_model_constants.F"; guard module_model_constants.o
objs=(stub_wrf.o oracle_io.o module_model_constants.o)

extract() {  # print routine $2 of file $1 from its header line to its END line
    awk -v want="$2" '
        function norm(s) { s = tolower(s); gsub(/\r/, "", s); gsub(/^[ \t]+/, "", s); return s }
        {
            l = norm($0)
            if (!inside && l ~ /^((real|integer)[^ \t]*[ \t]+)?(subroutine|function)[ \t]+/) {
                t = l; sub(/^.*(subroutine|function)[ \t]+/, "", t); sub(/[ \t(].*$/, "", t)
                if (t == want) inside = 1
            }
            if (inside) {
                print $0
                if (l ~ /^end[ \t]*(subroutine|function)/) { found = 1; exit }
            }
        }
        END { if (!found) exit 7 }' "$1"
}
out=activate_extract.F90
{
    echo "! GENERATED by build.sh from YOUR phys/module_mixactivate.F; never commit."
    echo "module activate_extract"
    echo "  implicit none"
    echo "  private"
    echo "  public :: activate"
    echo "contains"
} > "${out}"
while read -r name; do
    name="${name%%#*}"; name="$(echo "${name}" | xargs)"
    [[ -z "${name}" ]] && continue
    extract "${src}/phys/module_mixactivate.F" "${name}" >> "${out}" || {
        echo "routine ${name} not found" >&2; exit 7; }
done < "${here}/routines.list"
echo "end module activate_extract" >> "${out}"
${fc} -o activate_extract.o "${out}"; guard activate_extract.o
objs+=(activate_extract.o)

printf 'subroutine control(x, n)\n integer :: n, i\n real :: x(n)\n do i = 1, n\n  x(i) = exp(x(i))\n end do\nend subroutine\n' > control.f90
gfortran -c -Ofast -ftree-vectorize -o control.o control.f90
nm -u control.o | grep -q '_ZGV' || {
    echo "libmvec positive control produced no _ZGV symbol; the guard is vacuous" >&2; exit 5; }

for driver in "${here}"/run_*.F90; do
    name=$(basename "${driver}" .F90)
    ${fc} -o "${name}.o" "${driver}"; guard "${name}.o"
    gfortran ${ORACLE_COVERAGE:+--coverage} -o "${name}" "${objs[@]}" "${name}.o"
    rm -rf "${fixtures:?}/${name#run_}"
    mkdir -p "${fixtures}/${name#run_}"
    "./${name}" "${fixtures}/${name#run_}" > "${name}-stdout.txt"
    (cd "${fixtures}/${name#run_}" && find . \( -name '*.bin' -o -name MANIFEST.txt \) \
        | LC_ALL=C sort | xargs sha256sum > oracle-sha256sums.txt)
done

{
    echo "# gfortran: $(gfortran --version | head -1)"
    echo "# glibc:    $(ldd --version 2>&1 | head -1 || true)"
    echo "# -O0 libm symbols the reference calls:"
    grep -E 'expf|powf|logf|log10f|sqrtf|erff|exp$|log$|pow$|__powi|_ZGV' undefined-O0.txt | sort -u || true
} > libm-report.txt
cat "${here}/SOURCES.sha256" > oracle-source-sha256sums.txt
(cd "${here}" && sha256sum ./*.F90 ./*.list ./build.sh | sed 's#  \./#  optional/wrfchem_pnnl/oracle/activate/#') >> oracle-source-sha256sums.txt
echo "activate oracle built in ${build}; fixtures in ${fixtures}"
