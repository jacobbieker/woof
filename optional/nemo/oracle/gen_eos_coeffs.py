"""Write woof_nemo/eos_coeffs.py from NEMO 5.0.2's src/OCE/TRA/eosbn2.F90.

Part of the NEMO opt-in (CeCILL v2.0, ../LICENSE).  Reads the TEOS-10 and
EOS-80 cases of eos_init (every ``NAME = literal_wp`` line of the EOS*, ALP*
and BET* polynomial coefficients, and the four scale constants) and writes
them as Python data, each literal kept as NEMO spells it so Python's
correctly rounded float() gives gfortran's word.  Usage:

    python -I gen_eos_coeffs.py NEMO_SOURCE_ROOT OUT.py
"""
import re
import sys
from pathlib import Path

src = (Path(sys.argv[1]) / "src/OCE/TRA/eosbn2.F90").read_text(encoding="latin-1").splitlines()
start = next(i for i, l in enumerate(src) if l.strip().startswith("SUBROUTINE eos_init"))
cases, cur = {}, None
for line in src[start:]:
    s = line.split("!")[0].strip()
    m = re.match(r"CASE\(\s*(np_\w+)\s*\)", s)
    if m:
        cur = m.group(1)
        cases[cur] = {}
        continue
    if s.startswith(("END SELECT", "CASE DEFAULT")):
        cur = None
    if cur in ("np_teos10", "np_eos80"):
        m = re.match(r"(EOS\d{3}|ALP\d{3}|BET\d{3}|rdeltaS|r1_S0|r1_T0|r1_Z0)\s*=\s*(.+)$", s)
        if m:
            cases[cur][m.group(1)] = m.group(2).replace("_wp", "")
out = ['# WOOF-OPTIN: nemo', '"""NEMO 5.0.2 eos_init coefficients (TEOS-10, EOS-80), generated by',
       'oracle/gen_eos_coeffs.py from src/OCE/TRA/eosbn2.F90.  CeCILL v2.0."""', '']
for case in ("np_teos10", "np_eos80"):
    out.append(f"{case.upper()[3:]} = {{")
    for k, v in cases[case].items():
        out.append(f'    "{k}": {v},')
    out.append("}")
Path(sys.argv[2]).write_text("\n".join(out) + "\n", encoding="utf-8")
print({k: len(v) for k, v in cases.items() if k in ("np_teos10", "np_eos80")})
