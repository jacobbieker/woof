import numpy as np
import pytest

from woof.hex import mesh_rows
from woof.hex.cli import main as hex_main
from woof.hex.cull_door import CULL_ROLES, CullRefusal, check_parent_vertical
from woof.hex.register_door import RegisterRefusal, register_mesh
from woof.hex.vertical_door import REGIONAL_REFUSAL, VerticalDoorRefusal, mint_vertical

netCDF4 = pytest.importorskip("netCDF4")

EARTH_RADIUS_M = 6371229.0
#: Deliberately NOT 55: the level count must come from the vertical spec.
LEVELS = 7


def _engine() -> Path:
    from woof.hex.engines import MESH, EngineRefusal, resolve

    try:
        return resolve(MESH, None)
    except EngineRefusal as error:  # pragma: no cover - box-dependent
        pytest.skip(f"rw_mpas_mesh is not on the engine ladder: {error}")


def synthetic_static(grid: Path, out: Path) -> Path:
    """The grid, Earth-scaled, plus terrain and the slots a static carries."""

    shutil.copyfile(grid, out)
    with netCDF4.Dataset(str(out), "a") as ds:
        for name in ("dcEdge", "dvEdge", "nominalMinDc", "xCell", "yCell", "zCell",
                     "xEdge", "yEdge", "zEdge", "xVertex", "yVertex", "zVertex"):
            ds.variables[name][...] = np.asarray(ds.variables[name][...]) * EARTH_RADIUS_M
        for name in ("areaCell", "areaTriangle", "kiteAreasOnVertex"):
            ds.variables[name][...] = (
                np.asarray(ds.variables[name][...]) * EARTH_RADIUS_M ** 2
            )
        ds.setncattr("sphere_radius", EARTH_RADIUS_M)
        lat = np.asarray(ds.variables["latCell"][:])
        lon = np.asarray(ds.variables["lonCell"][:])
        ds.createVariable("ter", "f4", ("nCells",))[:] = (
            np.clip(np.sin(3.0 * lat) * np.cos(2.0 * lon), 0.0, None) * 2000.0
        ).astype("f4")
        for dim, size in (("TWO", 2), ("FIFTEEN", 15), ("R3", 3)):
            if dim not in ds.dimensions:
                ds.createDimension(dim, size)
        n_edges = len(ds.dimensions["nEdges"])
        ds.createVariable("deriv_two", "f4", ("nEdges", "TWO", "FIFTEEN"))[:] = (
            np.full((n_edges, 2, 15), 1.0e-12, dtype="f4")
        )
        for name, dims in (
            ("edgeNormalVectors", ("nEdges", "R3")),
            ("localVerticalUnitVectors", ("nCells", "R3")),
            ("cellTangentPlane", ("nCells", "TWO", "R3")),
            ("coeffs_reconstruct", ("nCells", "maxEdges", "R3")),
        ):
            ds.createVariable(name, "f4", dims)[...] = 0.0
    return out


def _generate(engine: Path, out: Path, background_km: float) -> Path:
    subprocess.run(
        [str(engine), "--background-km", str(background_km), "--out", str(out), "--clobber"],
        check=True, capture_output=True, text=True,
    )
    return out


@pytest.fixture(scope="module")
def chain(tmp_path_factory) -> SimpleNamespace:
    """Generate, mint the vertical, cull all three: once for the module."""

    engine = _engine()
    root = tmp_path_factory.mktemp("register-vertical")
    grid = _generate(engine, root / "g.grid.nc", 1000.0)
    static = synthetic_static(grid, root / "g.static.nc")
    spec = root / "vertical-spec.json"
    spec.write_text(json.dumps({
        "schema": "gpuwm-hex.vertical-spec/v1", "n_vert_levels": LEVELS,
        "ztop_m": 20000.0,
    }), encoding="utf-8")
    vertical = root / "g.vertical.nc"
    assert hex_main([
        "vertical", "--grid", str(grid), "--static", str(static),
        "--vertical-spec", str(spec), "-o", str(vertical),
    ]) == 0
    region = root / "region.json"
    region.write_text(json.dumps(
        {"kind": "cap", "center_deg": [40.0, -100.0], "radius_km": 4000.0}
    ), encoding="utf-8")
    cut = root / "cut"
    cut.mkdir()
    assert hex_main([
        "cull", "--parent-grid", str(grid), "--parent-static", str(static),
        "--parent-vertical", str(vertical), "--region", str(region),
        "--out-dir", str(cut), "--name", "c", "--engine", str(engine),
    ]) == 0
    return SimpleNamespace(
        engine=engine, root=root, grid=grid, static=static, spec=spec,
        vertical=vertical, region=region, cut=cut,
        cull_grid=cut / "c.grid.nc", cull_static=cut / "c.static.nc",
        cull_vertical=cut / "c.vertical.nc", cull_receipt=cut / "c.cull.json",
    )


def _quiet(*_args, **_kwargs) -> None:
    return None


def _register_pair(chain: SimpleNamespace, rows: Path, **extra) -> tuple:
    parent, _ = register_mesh(
        grid=chain.grid, static=chain.static, name="g1000", rows=rows,
        vertical_spec=chain.spec, log=_quiet,
    )
    cull, _ = register_mesh(
        grid=chain.cull_grid, static=chain.cull_static, name="c1000", rows=rows,
        parent_row="g1000", cull_receipt=chain.cull_receipt, log=_quiet, **extra,
    )
    return parent, cull


class Binding:
    def __init__(self, **kwargs):
        self.kwargs = kwargs
        self.name = kwargs["name"]


