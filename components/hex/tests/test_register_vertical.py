def test_the_culled_vertical_is_the_parent_restricted_to_the_cut_cells(chain) -> None:
    def coords(path: Path, kind: str) -> np.ndarray:
        with netCDF4.Dataset(str(path)) as ds:
            return np.stack([
                np.asarray(ds.variables[f"{axis}{kind}"][:], dtype=np.float64)
                for axis in ("x", "y", "z")
            ], axis=1)

    def lookup(parent: np.ndarray, child: np.ndarray) -> np.ndarray:
        scale = np.max(np.abs(parent))
        keys = {tuple(np.round(row / scale, 9)): i for i, row in enumerate(parent)}
        return np.array([keys[tuple(np.round(row / scale, 9))] for row in child])

    cells = lookup(coords(chain.vertical, "Cell"), coords(chain.cull_vertical, "Cell"))
    edges = lookup(coords(chain.vertical, "Edge"), coords(chain.cull_vertical, "Edge"))
    assert 0 < cells.size < 572
    with netCDF4.Dataset(str(chain.vertical)) as parent, \
            netCDF4.Dataset(str(chain.cull_vertical)) as child:
        assert len(child.dimensions["nVertLevels"]) == LEVELS
        for name in ("ter", "zgrid", "zz", "dss", "hx"):
            np.testing.assert_array_equal(
                np.asarray(child.variables[name][:]),
                np.asarray(parent.variables[name][:])[cells], err_msg=name,
            )
        for name in ("zxu", "zb", "zb3"):
            np.testing.assert_array_equal(
                np.asarray(child.variables[name][:]),
                np.asarray(parent.variables[name][:])[edges], err_msg=name,
            )
        for name in ("rdzw", "fzm", "fzp"):
            np.testing.assert_array_equal(
                np.asarray(child.variables[name][:]), np.asarray(parent.variables[name][:]),
            )
        # Lineage carried: the vertical stamp and spec digest survive the cut.
        assert child.getncattr("gpuwm_hex_vertical_spec_sha256") == \
            parent.getncattr("gpuwm_hex_vertical_spec_sha256")


def test_the_cull_receipt_records_digests_for_every_role(chain) -> None:
    receipt = json.loads(chain.cull_receipt.read_text(encoding="utf-8"))
    for role in ("grid", "static"):
        entry = receipt["files"][role]
        assert entry["out_sha256"] == mesh_rows.sha256_file(Path(entry["out"]))
        assert entry["parent_sha256"] == mesh_rows.sha256_file(Path(entry["parent"]))
    # No row pins the vertical (or an init), so the cull does not reread it.
    assert "out_sha256" not in receipt["files"]["vertical"]
    assert receipt["files"]["vertical"]["parent_vertical"]["n_vert_levels"] == LEVELS
    assert receipt["region_document"]["kind"] == "cap"


