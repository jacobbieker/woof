"""`woof hex register`, `woof hex vertical` and `woof hex cull --parent-vertical`.

The chain under test is the one a mesh generated by anything but the point
door has to walk to reach a forecast: mint the vertical on the GLOBAL
parent, cut grid + static + vertical with one region, register the parent,
register the cut against it.  The mesh is a real ``rw_mpas_mesh`` sphere
(572 cells, generated in a fraction of a second); the static is synthetic --
the grid Earth-scaled plus the terrain and the derived-geometry slots a real
static carries -- because a real one reads a 16 GB terrain archive.  Tests
that need the generator skip by name when it is not on the engine ladder.
"""

from __future__ import annotations

