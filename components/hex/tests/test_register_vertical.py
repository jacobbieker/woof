def test_register_refuses_mismatched_cull_digests(chain, tmp_path) -> None:
    rows = tmp_path / "r.json"
    register_mesh(grid=chain.grid, static=chain.static, name="g1000", rows=rows,
                  vertical_spec=chain.spec, log=_quiet)
    receipt = json.loads(chain.cull_receipt.read_text(encoding="utf-8"))
    tampered = json.loads(json.dumps(receipt))
    tampered["files"]["static"]["out_sha256"] = "0" * 64
    bad_out = tmp_path / "out.cull.json"
    bad_out.write_text(json.dumps(tampered), encoding="utf-8")
    with pytest.raises(RegisterRefusal) as refusal:
        register_mesh(grid=chain.cull_grid, static=chain.cull_static, name="c1", rows=rows,
                      parent_row="g1000", cull_receipt=bad_out, log=_quiet)
    assert "moved after the cull" in str(refusal.value)
    tampered = json.loads(json.dumps(receipt))
    tampered["files"]["grid"]["parent_sha256"] = "1" * 64
    bad_parent = tmp_path / "parent.cull.json"
    bad_parent.write_text(json.dumps(tampered), encoding="utf-8")
    with pytest.raises(RegisterRefusal) as refusal:
        register_mesh(grid=chain.cull_grid, static=chain.cull_static, name="c1", rows=rows,
                      parent_row="g1000", cull_receipt=bad_parent, log=_quiet)
    assert "was not cut from that parent" in str(refusal.value)
    for role in ("grid", "static"):
        receipt["files"][role].pop("out_sha256")
    old = tmp_path / "old.cull.json"
    old.write_text(json.dumps(receipt), encoding="utf-8")
    with pytest.raises(RegisterRefusal) as refusal:
        register_mesh(grid=chain.cull_grid, static=chain.cull_static, name="c1", rows=rows,
                      parent_row="g1000", cull_receipt=old, log=_quiet)
    assert "re-run" in str(refusal.value)


