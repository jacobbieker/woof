def test_register_writes_a_global_and_a_cull_row_that_round_trip_and_bind(chain, tmp_path) -> None:
    rows = tmp_path / "mesh-rows.json"
    parent, cull = _register_pair(chain, rows)
    assert parent.kind == "generated-global" and parent.point_deg is None
    assert parent.n_levels == LEVELS and cull.n_levels == LEVELS
    assert parent.timestep_evidence == mesh_rows.ANCHORED_TIMESTEP_EVIDENCE
    assert parent.dt_seconds in {120.0, 100.0, 75.0}
    # The spec is the one the generator stamped on the grid.
    assert parent.region["background_km"] == 1000.0 and parent.spec_sha256
    with netCDF4.Dataset(str(chain.static)) as ds:
        assert parent.nominal_dx_m == float(np.float32(ds.variables["nominalMinDc"][:]))
    assert cull.parent_row == "g1000" and cull.boundary_zone_width == 7
    assert cull.cull_receipt == str(chain.cull_receipt.absolute())
    assert cull.cull_region["kind"] == "cap" and cull.cull_pad_scale is None
    assert mesh_rows.read_rows(rows) == [parent, cull]
    assert mesh_rows.GENERATED_GLOBAL_ROW_MARKER in parent.notes()
    assert mesh_rows.CULL_ROW_MARKER in cull.notes()
    patched = mesh_rows.apply_rows({}, Binding, rows)
    assert patched["c1000"].kwargs["boundary_zone_width"] == 7
    assert patched["g1000"].kwargs["n_levels"] == LEVELS


