"""The fast numerics' binary64 on Metal: df64 (woof/backend/metal/f64_df64.h).

THE BREAKAGES THESE PREVENT
---------------------------
1. Strict numerics changing: its translation must be the soft-float text,
   byte for byte, whatever the df64 code path does.
2. A fast unit silently keeping soft-float (the slow cold compile df64
   exists to remove), or a strict unit silently taking df64.
3. The header's generated constants drifting from tools/df64_constants.py.
4. df64 division or square root leaving the correctly rounded word, or the
   df64 libm leaving its stated bound (tools/df64_grade.py's host leg, on a
   host with x87 long double).
5. The GPU computing other words than the graded host build of the same
   text (the GPU leg), and a translated unit's doubles going wrong.
"""

from __future__ import annotations

import importlib.util
import platform
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import df64_constants  # noqa: E402

HEADER = ROOT / "woof" / "backend" / "metal" / "f64_df64.h"


def test_header_carries_the_generated_constants():
    text = HEADER.read_text(encoding="utf-8")
    start = text.index("// ---- generated by")
    end = text.index("// ---- end generated") + len("// ---- end generated")
    assert text[start:end] == df64_constants.block()


def test_strict_prelude_is_the_soft_float_text():
    from woof.backend.translate import prelude
    for contract in (False, True):
        for retain in (False, True):
            soft = prelude(contract=contract, retain_subnormals=retain)
            assert prelude(contract=contract, retain_subnormals=retain, f64="soft") == soft
            assert "f64_df_div" not in soft and "df_exp_word" not in soft
            fast = prelude(contract=contract, retain_subnormals=retain, f64="df64")
            assert "#define WOOF_DF64_ARITH 1" in fast and "df_exp_word(a.b)" in fast
            # the df64 text sits beside the soft-float text, which it falls back on
            assert "F64_OP f64_u64 f64_div(" in fast
    with pytest.raises(ValueError):
        prelude(contract=False, f64="quad")


def test_df64_compose_keeps_only_the_non_native_vendor_names():
    from woof.backend.translate import DF64_NATIVE, compose
    src = "__device__ double f(double x) { return exp(x) + tgamma(x); }"
    soft = compose(src)
    fast = compose(src, None, "df64")
    assert "double exp(double x) { return wcr_exp(x); }" in soft
    assert "double exp(double x)" not in fast
    assert "double tgamma(double x) { return wlm_tgamma(x); }" in fast
    for name in DF64_NATIVE:
        assert f"__forceinline__ double {name}(" not in fast
    # a unit calling only df64-native names gets no vendored text at all
    assert compose("__device__ double g(double x) { return pow(x, cbrt(x)); }", None, "df64").startswith("__device__ double g")


def test_f64_mode_follows_the_numerics(monkeypatch):
    from woof import numerics
    from woof.backend.metal import loader
    monkeypatch.delenv("WOOF_METAL_F64", raising=False)
    monkeypatch.setattr(numerics, "is_strict", lambda: True)
    assert loader.f64_mode("u", "", ()) == "soft"
    monkeypatch.setattr(numerics, "is_strict", lambda: False)
    assert loader.f64_mode("u", "", ()) == "df64"
    assert loader.f64_mode("u", "", ("-DGPUWM_PREPARATION_IDENTITY=1",)) == "soft"
    monkeypatch.setattr(loader, "SOFT_F64_UNITS", frozenset({"u"}))
    assert loader.f64_mode("u[3]", "", ()) == "soft"
    monkeypatch.setattr(loader, "SOFT_F64_UNITS", frozenset())
    monkeypatch.setenv("WOOF_METAL_F64", "soft")
    assert loader.f64_mode("u", "", ()) == "soft"
    monkeypatch.setenv("WOOF_METAL_F64", "fast")
    with pytest.raises(ValueError):
        loader.f64_mode("u", "", ())


@pytest.mark.skipif(platform.machine() not in ("x86_64", "AMD64")
                    or not (shutil.which("clang++") or shutil.which("g++")),
                    reason="the host leg needs x87 long double and a C++ compiler")
def test_host_grade_within_bounds():
    out = subprocess.run([sys.executable, str(ROOT / "tools" / "df64_grade.py"), "host", "--samples", "100000"],
                         capture_output=True, text=True)
    assert out.returncode == 0, out.stdout[-4000:] + out.stderr[-2000:]
    assert '"div": {"n": 100000, "max_ulp": 0.0' in out.stdout


_mlx = pytest.mark.skipif(importlib.util.find_spec("mlx") is None, reason="needs mlx (Apple silicon)")


@_mlx
@pytest.mark.skipif(not (shutil.which("clang++") or shutil.which("c++")), reason="needs a C++ compiler")
def test_gpu_words_are_the_host_words():
    out = subprocess.run([sys.executable, str(ROOT / "tools" / "df64_grade.py"), "gpu", "--samples", "65536"],
                         capture_output=True, text=True, cwd=ROOT)
    assert out.returncode == 0, out.stdout[-4000:] + out.stderr[-2000:]


_KERNEL = r'''
extern "C" __global__ void dbl(const double* x, const double* y, double* out, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i >= n) return;
    double a = x[i], b = y[i];
    out[0 * n + i] = a / b;
    out[1 * n + i] = sqrt(a);
    out[2 * n + i] = exp(b);
    out[3 * n + i] = log(a);
    out[4 * n + i] = pow(a, b);
    out[5 * n + i] = sin(a) + cos(b);
    out[6 * n + i] = atan2(b, a);
    out[7 * n + i] = a * b + a;
}
'''


@_mlx
def test_a_translated_unit_in_fast_numerics(monkeypatch):
    from woof import backend, numerics
    if backend.active() != "mlx":
        pytest.skip("runs under WOOF_BACKEND=mlx")
    if numerics.is_strict():
        pytest.skip("fast numerics only")
    import cupy as cp
    from woof.backend.metal import loader
    unit = loader.translate_unit("df64_probe", _KERNEL)
    assert "#define WOOF_DF64_ARITH 1" in unit.msl
    rng = np.random.default_rng(7)
    n = 4096
    x = rng.uniform(0.01, 100.0, n)
    y = rng.uniform(-5.0, 5.0, n)
    out = cp.zeros(8 * n, dtype=cp.float64)
    fn = cp.RawKernel(_KERNEL, "dbl")
    fn(((n + 127) // 128,), (128,), (cp.asarray(x), cp.asarray(y), out, np.int32(n)))
    got = cp.asnumpy(out).reshape(8, n)
    # division, square root and a * b + a: the correctly rounded words
    assert np.array_equal(got[0].view(np.uint64), (x / y).view(np.uint64))
    assert np.array_equal(got[1].view(np.uint64), np.sqrt(x).view(np.uint64))
    assert np.array_equal(got[7].view(np.uint64), (x * y + x).view(np.uint64))
    # the df64 libm: within its graded bound (256 ulps, about 2^-44 relative)
    want = [np.exp(y), np.log(x), np.power(x, y), np.sin(x) + np.cos(y), np.arctan2(y, x)]
    for k, (g, w) in enumerate(zip(got[2:7], want)):
        scale = 2.0 if k == 3 else np.maximum(np.abs(w), 1e-300)   # sin + cos may cancel
        rel = np.abs(g - w) / scale
        assert rel.max() < 2.0 ** -40, rel.max()
