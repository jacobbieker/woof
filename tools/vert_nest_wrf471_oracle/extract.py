"""Cut WRF v4.7.1's vertical-nesting code out of its files verbatim.

    python extract.py <WRF_SOURCE_ROOT> <OUT_DIR>

WRF's vertical grid nesting (``vert_refine_method /= 0``) lives in pieces
that cannot be compiled on their own: the column routines in
``share/interp_fcn.F`` are free-standing, but the reference-coordinate
block and the post-interpolation rebalance sit inside
``force_domain_em_part2`` (``external/RSL_LITE``), which needs WRF's whole
domain type, communication layer and generated include files.  This copies
the blocks the port transcribes, after checking the sha256 of every file
and of every block, so the oracle compiles WRF's own statements:

* ``share/interp_fcn.F:1910-2152`` -- ``vert_interp_vert_nesting`` (mass
  and u/v points), ``vert_interp_vert_nesting_w`` (w points),
  ``vert_interp_vert_nesting_1d``, ``inter_wrf_copy`` and
  ``coeff_mon_wrf_copy`` (the monotone cubic), into one module;
* ``dyn_em/nest_init_utils.F:1033-1184`` -- ``compute_vcoord_1d_coeffs``
  (the hybrid c1..c4 of a ladder), which the driver uses to build both
  ladders' coefficients the way WRF builds them;
* ``dyn_em/nest_init_utils.F:388-409`` -- the dn/rdn/fnp/fnm and the
  cf1..cfn1 extrapolation constants of an arbitrary ladder
  (``vert_cor_vertical_nesting_arbitrary``), as an include;
* ``external/RSL_LITE/force_domain_em_part2.F:73-109`` -- the reference
  log-pressure heights (``alt_u_c``, ``alt_w_c``, ``alt_u_n``,
  ``alt_w_n``) both ladders are interpolated in, as an include;
* ``external/RSL_LITE/force_domain_em_part2.F:124-303`` -- the vertical
  interpolation call site and the rebalance of t_2, QV and ph_2 on the
  intermediate grid, as an include.  Its own ``#include
  "nest_forcedown_interp_vert.inc"`` (generated by WRF's registry tool
  from ``tools/gen_interp.c:540-640``) is written by ``build.sh`` with
  the calls that tool would emit for the fields the oracle carries.

The includes are expanded inside subroutines whose dummy arguments carry
WRF's own names (``grid%...``, ``ngrid%...``, ``pgrid%...``,
``config_flags%...``, ``moist``), so the statements paste unmodified.

WRF v4.7.1 is tag v4.7.1, commit f52c197ed39d12e087d02c50f412d90d418f6186,
public domain.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

WRF_COMMIT = "f52c197ed39d12e087d02c50f412d90d418f6186"

FILES = {
    "share/interp_fcn.F":
        "680881db48904396f38856ca1dd2578a84e8eb0a9cdd05d49f4c63cd8ce9bdaa",
    "dyn_em/nest_init_utils.F":
        "07db287108ab031f89e8bb80d830871daf8ba962f60d394e1ff31c845c1b4a14",
    "external/RSL_LITE/force_domain_em_part2.F":
        "768d95ef689a6e38a69c2bc8fd822c71b24a4811d4620aa62db38e951cd7ebe9",
}

#: (output, file, first line, last line, sha256 of the lines, LF-joined).
BLOCKS = (
    ("vert_routines", "share/interp_fcn.F", 1910, 2152,
     "5313e14d43c93a2650786adedd5fd312d1463198f1445b19ad65327e33da5fb6"),
    ("vcoord", "dyn_em/nest_init_utils.F", 1033, 1184,
     "3afe9234bf67ac5571e4e5bcc1ccb51ce78eb285f1c8252bc150f9ed14a30cf0"),
    ("dn_cf", "dyn_em/nest_init_utils.F", 388, 409,
     "875a549dac9c40bc7cd37bf715bc9aae36422eb8f3caeba408667a7709ce87d7"),
    ("alt", "external/RSL_LITE/force_domain_em_part2.F", 73, 109,
     "62c06fd22f8530dca5fa3153303f77a7fbaf1d0a3efc87f87422329d13ae1a6a"),
    ("rebalance", "external/RSL_LITE/force_domain_em_part2.F", 124, 303,
     "d6a4f3569d89fae4bdf244fa592886a9df4e9746b0321adfe5182836745e453a"),
)

_VERT_MODULE = """MODULE wrf_vert_nest_interp
  IMPLICIT NONE
CONTAINS
{vert_routines}END MODULE wrf_vert_nest_interp
"""

_VCOORD_MODULE = """MODULE wrf_vcoord
  IMPLICIT NONE
CONTAINS
  SUBROUTINE wrf_message(text)
    CHARACTER(LEN=*), INTENT(IN) :: text
    WRITE(*,'(A)') TRIM(text)
  END SUBROUTINE wrf_message
  SUBROUTINE wrf_error_fatal(text)
    CHARACTER(LEN=*), INTENT(IN) :: text
    WRITE(*,'(A)') TRIM(text)
    ERROR STOP 1
  END SUBROUTINE wrf_error_fatal
{vcoord}END MODULE wrf_vcoord
"""


def _block(root: Path, path: str, name: str, first: int, last: int,
           digest: str) -> str:
    lines = (root / path).read_bytes().split(b"\n")
    text = b"\n".join(lines[first - 1:last]) + b"\n"
    got = hashlib.sha256(text).hexdigest()
    if got != digest:
        raise SystemExit(f"{path}:{first}-{last} ({name}) is not the pinned "
                         f"block: sha256 {got}, expected {digest}")
    return text.decode("ascii")


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    root, out = Path(argv[1]), Path(argv[2])
    for path, digest in FILES.items():
        got = hashlib.sha256((root / path).read_bytes()).hexdigest()
        if got != digest:
            raise SystemExit(f"{path} is not WRF v4.7.1's: sha256 {got}")
    blocks = {name: _block(root, path, name, first, last, digest)
              for name, path, first, last, digest in BLOCKS}
    out.mkdir(parents=True, exist_ok=True)
    (out / "wrf_vert_nest_interp.F90").write_text(
        _VERT_MODULE.format(vert_routines=blocks["vert_routines"]),
        encoding="ascii")
    (out / "wrf_vcoord.F90").write_text(
        _VCOORD_MODULE.format(vcoord=blocks["vcoord"]), encoding="ascii")
    for name in ("dn_cf", "alt", "rebalance"):
        (out / f"wrf_{name}.inc").write_text(blocks[name], encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
