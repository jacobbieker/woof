// SINCOS_TABLE_LOOKUP: (sn, ssn, cs, ccs) at the table point of u
__device__ __forceinline__ void lookup(double u, double &sn, double &ssn, double &cs, double &ccs) {
    const int k = ((int)(unsigned int)g239_w(u)) << 2;
    sn = g239_d(SINCOSTAB[k]);
    ssn = g239_d(SINCOSTAB[k + 1]);
    cs = g239_d(SINCOSTAB[k + 2]);
    ccs = g239_d(SINCOSTAB[k + 3]);
}

// do_cos: cos(x + dx) from the table point and short Taylor series
__device__ __forceinline__ double do_cos(double x, double dx) {
    if (x < 0.0) dx = -dx;
    const double ax = fabs(x);
    const double u = g239_add(G239_BIG, ax);
    const double y = g239_add(g239_sub(ax, g239_sub(u, G239_BIG)), dx);
    const double xx = g239_mul(y, y);
    const double s = g239_fma(g239_mul(y, xx), g239_fma(xx, G239_SN5, G239_SN3), y);
    const double c = g239_mul(xx, g239_fma(xx, g239_fma(xx, G239_CS6, G239_CS4), G239_CS2));
    double sn, ssn, cs, ccs;
    lookup(u, sn, ssn, cs, ccs);
    const double cor = g239_fma(-sn, s, g239_fma(-cs, c, g239_fma(-s, ssn, ccs)));
    return g239_add(cs, cor);
}

// do_sin: sin(x + dx); TAYLOR_SIN below 0.126, else the table
__device__ __forceinline__ double do_sin(double x, double dx) {
    const double xold = x;
    if (fabs(x) < 0.126) {
        const double xx = g239_mul(x, x);
        const double p = g239_fma(g239_fma(g239_fma(g239_fma(G239_S5, xx, G239_S4), xx, G239_S3), xx, G239_S2),
                                  xx, G239_S1);
        const double t = g239_fma(xx, g239_fma(p, x, -g239_mul(0.5, dx)), dx);
        return g239_add(x, t);
    }
    if (x <= 0.0) dx = -dx;
    const double ax = fabs(x);
    const double u = g239_add(G239_BIG, ax);
    const double y = g239_sub(ax, g239_sub(u, G239_BIG));
    const double xx = g239_mul(y, y);
    const double s = g239_add(y, g239_fma(g239_mul(y, xx), g239_fma(xx, G239_SN5, G239_SN3), dx));
    const double c = g239_fma(y, dx, g239_mul(xx, g239_fma(xx, g239_fma(xx, G239_CS6, G239_CS4), G239_CS2)));
    double sn, ssn, cs, ccs;
    lookup(u, sn, ssn, cs, ccs);
    const double cor = g239_fma(s, cs, g239_fma(-c, sn, g239_fma(s, ccs, ssn)));
    return copysign(g239_add(sn, cor), xold);
}

// reduce_sincos: |x| < 105414350 as n*pi/2 + (a + da); returns n mod 4
__device__ __forceinline__ int reduce_sincos(double x, double &a, double &da) {
    const double t = g239_fma(x, G239_HPINV, G239_TOINT);
    const double xn = g239_sub(t, G239_TOINT);
    const double y = g239_fma(-xn, G239_MP2, g239_fma(-xn, G239_MP1, x));
    const int n = (int)((unsigned int)g239_w(t) & 3u);
    const double t2 = g239_fma(-xn, G239_PP3, y);
    double db = g239_fma(-xn, G239_PP3, g239_sub(y, t2));
    const double b = g239_fma(-xn, G239_PP4, t2);
    db = g239_add(db, g239_fma(-xn, G239_PP4, g239_sub(t2, b)));
    a = b;
    da = db;
    return n;
}

