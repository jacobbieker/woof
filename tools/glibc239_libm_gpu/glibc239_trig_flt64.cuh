#define G239_TWO52 4503599627370496.0
#define G239_D3 g239_d(0xbfd5555555555555ULL)
#define G239_D5 g239_d(0x3fc99999999997fdULL)
#define G239_D7 g239_d(0xbfc24924923f7603ULL)
#define G239_D9 g239_d(0x3fbc71c6e5129a3bULL)
#define G239_D11 g239_d(0xbfb7458022b13c25ULL)
#define G239_D13 g239_d(0x3fb375f08b31cbceULL)
#define G239_A g239_d(0x3e4bb67a00000000ULL)
#define G239_B g239_d(0x3fb0000000000000ULL)
#define G239_C g239_d(0x3ff0000000000000ULL)
#define G239_D g239_d(0x4030000000000000ULL)
#define G239_E g239_d(0x43349ff200000000ULL)
#define G239_HPI g239_d(0x3ff921fb54442d18ULL)
#define G239_MHPI g239_d(0xbff921fb54442d18ULL)
#define G239_HPI1 g239_d(0x3c91a62633145c07ULL)

__device__ __forceinline__ double cij(int i, int j) { return g239_d(CIJ[i][j]); }
// the table row for u in [1/16, 1): (TWO52 + 256 u) - TWO52 - 16, the sum fused
__device__ __forceinline__ int row(double u) {
    return (int)g239_sub(g239_fma(u, 256.0, G239_TWO52), G239_TWO52) - 16;
}
__device__ __forceinline__ double poly_d(double v) {
    double yy = g239_fma(v, G239_D13, G239_D11);
    yy = g239_fma(v, yy, G239_D9);
    yy = g239_fma(v, yy, G239_D7);
    yy = g239_fma(v, yy, G239_D5);
    return g239_fma(v, yy, G239_D3);
}
__device__ __forceinline__ double table_poly(double z, int i) {
    double yy = g239_fma(z, cij(i, 6), cij(i, 5));
    yy = g239_fma(z, yy, cij(i, 4));
    yy = g239_fma(z, yy, cij(i, 3));
    return g239_fma(z, yy, cij(i, 2));
}

// glibc 2.39's binary64 atan (__atan_fma)
__device__ __forceinline__ double g239_atan(double x) {
    const unsigned long long bits = g239_w(x);
    const unsigned int ux = (unsigned int)(bits >> 32), dx = (unsigned int)bits;
    if ((ux & 0x7ff00000u) == 0x7ff00000u && ((ux & 0x000fffffu) | dx) != 0u)
        return g239_d(bits | 0x0008000000000000ULL);                 // x + x on SSE: the quieted NaN
    const double u = x < 0.0 ? -x : x;
    if (u < G239_C) {
        if (u < G239_B) {
            if (u < G239_A) return x;
            const double v = g239_mul(x, x);
            return g239_fma(g239_mul(x, v), poly_d(v), x);
        }
        const int i = row(u);
        const double z = g239_sub(u, cij(i, 0));
        const double y = g239_fma(table_poly(z, i), z, cij(i, 1));
        return copysign(y, x);
    }
    if (u < G239_D) {
        const double w = g239_div(1.0, u);
        const double t1 = g239_mul(w, u), t2 = g239_fma(w, u, -t1);
        const int i = row(w);
        const double z = g239_fma(w, g239_sub(g239_sub(1.0, t1), t2), g239_sub(w, cij(i, 0)));
        const double yy = g239_fma(-z, table_poly(z, i), G239_HPI1);
        return copysign(g239_add(g239_sub(G239_HPI, cij(i, 1)), yy), x);
    }
    if (u < G239_E) {
        const double w = g239_div(1.0, u);
        const double v = g239_mul(w, w);
        const double t1 = g239_mul(w, u), t2 = g239_fma(w, u, -t1);
        const double yy = poly_d(v);
        const double t3 = g239_sub(G239_HPI, w);
        const double cor = fabs(G239_HPI) > fabs(w) ? g239_sub(g239_sub(G239_HPI, t3), w)
                                                    : g239_sub(G239_HPI, g239_add(w, t3));
        const double r = g239_fma(-g239_mul(w, v), yy, g239_fma(-w, g239_sub(g239_sub(1.0, t1), t2),
                                                                g239_add(G239_HPI1, cor)));
        return copysign(g239_add(t3, r), x);
    }
    return x > 0.0 ? G239_HPI : G239_MHPI;
}

