__device__ __forceinline__ double asn(int n) { return g239_d(ASNCS[n]); }
// f1 + x2*(f2 + x2*(f3 + x2*(f4 + x2*(f5 + x2*f6)))), all five fused
__device__ __forceinline__ double asin_fpoly(double x2) {
    double p = g239_fma(G239_AS_F6, x2, G239_AS_F5);
    p = g239_fma(p, x2, G239_AS_F4);
    p = g239_fma(p, x2, G239_AS_F3);
    p = g239_fma(p, x2, G239_AS_F2);
    return g239_fma(p, x2, G239_AS_F1);
}
// the table ranges: a[n+1]*xx + (xx*xx*(a[n+2] + ... + xx*a[n+deg]) + a[n+deg+1]),
// every Horner step and both outer products fused; the caller adds a[n+deg+2]
__device__ __forceinline__ double asin_tpoly(double xx, int n, int deg) {
    double q = asn(n + deg);
    for (int i = deg - 1; i >= 2; --i) q = g239_fma(q, xx, asn(n + i));
    const double p = g239_fma(g239_mul(xx, xx), q, asn(n + deg + 1));
    return g239_fma(xx, asn(n + 1), p);
}
// the table range of k = |x|'s high word, 0.125 <= |x| < 0.96875
__device__ __forceinline__ void asin_range(unsigned int k, int &n, int &deg) {
    if (k < 0x3fe00000u) {
        n = k < 0x3fd00000u ? (int)(11u * ((k & 0x000fffffu) >> 15))
                            : (int)(11u * ((k & 0x000fffffu) >> 14) + 352u);
        deg = 6;
    } else if (k < 0x3fe80000u) {
        n = 1056 + (int)(((k & 0x000fe000u) >> 11) * 3u); deg = 7;
    } else if (k < 0x3fed8000u) {
        n = 992 + (int)(((k & 0x000fe000u) >> 13) * 13u); deg = 8;
    } else if (k < 0x3fee8000u) {
        n = 884 + (int)(((k & 0x000fe000u) >> 13) * 14u); deg = 9;
    } else {
        n = 768 + (int)(((k & 0x000fe000u) >> 13) * 15u); deg = 10;
    }
}

// glibc 2.39's binary64 asin (__ieee754_asin as e_asin-fma.c, behind the
// wrapper's |x| > 1 domain check)
__device__ __forceinline__ double g239_asin(double x) {
    const unsigned long long u = g239_w(x);
    const int m = (int)(unsigned int)(u >> 32);
    const unsigned int k = (unsigned int)m & 0x7fffffffu;
    if (k < 0x3e500000u) return x;
    if (k < 0x3fc00000u) {
        const double x2 = g239_mul(x, x);
        return g239_fma(asin_fpoly(x2), g239_mul(x, x2), x);
    }
    if (k < 0x3fef0000u) {
        int n, deg;
        asin_range(k, n, deg);
        const double xx = m > 0 ? g239_sub(x, asn(n)) : g239_sub(-x, asn(n));
        const double res = g239_add(asn(n + deg + 2), asin_tpoly(xx, n, deg));
        return m > 0 ? res : -res;
    }
    if (k < 0x3ff00000u) {
        const double z = g239_mul(0.5, m > 0 ? g239_sub(1.0, x) : g239_add(1.0, x));
        const unsigned int kz = (unsigned int)(g239_w(z) >> 32);
        double t = g239_mul(g239_d(INROOT[(kz & 0x001fffffu) >> 14]), g239_d(POWTWO[511u - (kz >> 21)]));
        const double r = g239_fma(-g239_mul(t, t), z, 1.0);
        t = g239_mul(t, g239_fma(g239_fma(g239_fma(G239_AS_RT3, r, G239_AS_RT2), r, G239_AS_RT1), r, G239_AS_RT0));
        const double c = g239_mul(t, z);
        const double h = g239_fma(-g239_mul(0.5, t), c, 1.5);
        const double y = g239_sub(g239_add(c, G239_AS_T24), G239_AS_T24);
        const double cc = g239_div(g239_fma(-y, y, z), g239_fma(h, c, y));
        const double p = g239_mul(asin_fpoly(z), z);
        const double cor = g239_fma(-g239_mul(2.0, g239_add(y, cc)), p, g239_fma(-2.0, cc, G239_AS_HP1));
        const double res = g239_add(g239_fma(-2.0, y, G239_AS_HP0), cor);
        return m > 0 ? res : -res;
    }
    if (k == 0x3ff00000u && (unsigned int)u == 0u) return m > 0 ? G239_AS_HP0 : -G239_AS_HP0;
    return g239_div(g239_sub(x, x), g239_sub(x, x));                 // |x| > 1 or NaN: a NaN
}

