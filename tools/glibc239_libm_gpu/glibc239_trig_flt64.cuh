// one half of the split argument times 2/pi: returns sum, sets b, bb
__device__ __forceinline__ double reduce_part(double xp, double &b_out, double &bb_out) {
    double r[6];
    double sum = 0.0;
    int k = (int)((g239_w(xp) >> 52) & 2047ULL);
    k = (k - 450) / 24;
    if (k < 0) k = 0;
    double gor = g239_d(G239_T576 - ((unsigned long long)(k * 24) << 52));
    for (int i = 0; i < 6; ++i) {
        r[i] = g239_mul(g239_mul(xp, TOVERP[k + i]), gor);
        gor = g239_mul(gor, G239_TM24);
    }
    for (int i = 0; i < 3; ++i) {
        const double s = g239_sub(g239_add(r[i], G239_RBIG), G239_RBIG);
        sum = g239_add(sum, s);
        r[i] = g239_sub(r[i], s);
    }
    double t = 0.0;
    for (int i = 0; i < 6; ++i) t = g239_add(t, r[5 - i]);
    double bb = g239_add(g239_add(g239_add(g239_add(g239_add(g239_sub(r[0], t), r[1]), r[2]), r[3]), r[4]), r[5]);
    double s = g239_sub(g239_add(t, G239_RBIG), G239_RBIG);
    sum = g239_add(sum, s);
    t = g239_sub(t, s);
    const double b = g239_add(t, bb);
    bb = g239_add(g239_sub(t, b), bb);
    s = g239_sub(g239_add(sum, G239_RBIG1), G239_RBIG1);
    sum = g239_sub(sum, s);
    b_out = b;
    bb_out = bb;
    return sum;
}

// __branred: x = n*pi/2 + (a + aa), |a + aa| < pi/4; returns n mod 4
__device__ __forceinline__ int branred(double x, double &a, double &aa) {
    x = g239_mul(x, G239_TM600);
    double t = g239_mul(x, G239_SPLIT);
    const double x1 = g239_sub(t, g239_sub(t, x));
    const double x2 = g239_sub(x, x1);
    double b1, bb1, b2, bb2;
    const double sum1 = reduce_part(x1, b1, bb1);
    const double sum2 = reduce_part(x2, b2, bb2);
    double sum = g239_add(sum1, sum2);
    double b = g239_add(b1, b2);
    const double bb = fabs(b1) > fabs(b2) ? g239_add(g239_sub(b1, b), b2) : g239_add(g239_sub(b2, b), b1);
    if (b > 0.5) {
        b = g239_sub(b, 1.0);
        sum = g239_add(sum, 1.0);
    } else if (b < -0.5) {
        b = g239_add(b, 1.0);
        sum = g239_sub(sum, 1.0);
    }
    double s = g239_add(b, g239_add(g239_add(bb, bb1), bb2));
    t = g239_add(g239_add(g239_sub(b, s), bb), g239_add(bb1, bb2));
    b = g239_mul(s, G239_SPLIT);
    const double t1 = g239_sub(b, g239_sub(b, s));
    const double t2 = g239_sub(s, t1);
    b = g239_mul(s, G239_HP0);
    const double bbb = g239_add(
        g239_add(g239_add(g239_sub(g239_mul(t1, G239_MP1), b), g239_mul(t1, G239_RMP2)), g239_mul(t2, G239_MP1)),
        g239_add(g239_add(g239_mul(t2, G239_RMP2), g239_mul(s, G239_HP1)), g239_mul(t, G239_HP0)));
    s = g239_add(b, bbb);
    t = g239_add(g239_sub(b, s), bbb);
    a = s;
    aa = t;
    return ((int)sum) & 3;
}

__device__ __forceinline__ double do_sincos(double a, double da, int n) {
    const double r = (n & 1) ? do_cos(a, da) : do_sin(a, da);
    return (n & 2) ? -r : r;
}

// glibc 2.39's binary64 sin (__sin_fma)
__device__ __forceinline__ double g239_sin(double x) {
    const unsigned int k = (unsigned int)(g239_w(x) >> 32) & 0x7fffffffu;
    double a, da;
    if (k < 0x3e500000u) return x;                                   // |x| < 2^-26
    if (k < 0x3feb6000u) return do_sin(x, 0.0);                      // |x| < 0.855469
    if (k < 0x400368fdu) return copysign(do_cos(g239_sub(G239_HP0, fabs(x)), G239_HP1), x);  // < 2.426265
    if (k < 0x419921fbu) { const int n = reduce_sincos(x, a, da); return do_sincos(a, da, n); }  // < 105414350
    if (k < 0x7ff00000u) { const int n = branred(x, a, da); return do_sincos(a, da, n); }
    return g239_div(x, x);
}

// glibc 2.39's binary64 cos (__cos_fma)
__device__ __forceinline__ double g239_cos(double x) {
    const unsigned int k = (unsigned int)(g239_w(x) >> 32) & 0x7fffffffu;
    double a, da;
    if (k < 0x3e400000u) return 1.0;                                 // |x| < 2^-27
    if (k < 0x3feb6000u) return do_cos(x, 0.0);                      // |x| < 0.855469
    if (k < 0x400368fdu) {                                           // |x| < 2.426265
        const double y = g239_sub(G239_HP0, fabs(x));
        a = g239_add(y, G239_HP1);
        da = g239_add(g239_sub(y, a), G239_HP1);
        return do_sin(a, da);
    }
    if (k < 0x419921fbu) { const int n = reduce_sincos(x, a, da); return do_sincos(a, da, n + 1); }
    if (k < 0x7ff00000u) { const int n = branred(x, a, da); return do_sincos(a, da, n + 1); }
    return g239_div(x, x);
}

