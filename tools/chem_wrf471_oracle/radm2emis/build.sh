#!/usr/bin/env bash
# Build and run the RADM2/SORGAM anthropogenic emission oracle (chem_opt = 1/2,
# emiss_opt = 3) against WRF v4.7.1.
#
#   bash tools/chem_wrf471_oracle/radm2emis/build.sh WRF_SRC BUILD_DIR [FIXTURE_ROOT]
#
# share/module_model_constants.F, chem/module_data_radm2.F,
# chem/module_data_sorgam.F and chem/module_emissions_anthropogenics.F compile
# whole and unchanged.  The routines in routines.list (aerosols_sorgam_init
# and sorgam_addemiss) are copied BYTE FOR BYTE from
# chem/module_aerosols_sorgam.F into one wrapper module, named
# module_aerosols_sorgam because module_emissions_anthropogenics.F's
# add_biogenics USEs it, after prelude.inc (the module's own USE lines and
# IMPLICIT NONE).  Nothing is edited.
#
# stub_radm2emis.F90 supplies only the Registry-generated
# module_state_description / module_configure (radm2sorg chem rows, eradmsorg
# emission rows) and stubs for the branches no case takes.  -O0, and the
# build fails if any -O0 object imports a libmvec _ZGV* symbol (positive
# control included).
set -euo pipefail
if [[ $# -lt 2 ]]; then
    echo "usage: build.sh WRF_SRC BUILD_DIR [FIXTURE_ROOT]" >&2
    exit 2
fi
src=$(realpath "$1")
build=$(realpath -m "$2")
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
fixtures=$(realpath -m "${3:-${build}/fixtures}")

while read -r sum rel; do
    [[ -z "${sum}" || "${sum}" == \#* ]] && continue
    got=$(sha256sum "${src}/${rel}" | cut -d' ' -f1)
    if [[ "${got}" != "${sum}" ]]; then
        echo "${rel}: sha256 ${got}, pinned ${sum}" >&2
        exit 3
    fi
done < "${here}/SOURCES.sha256"

mkdir -p "${build}" "${fixtures}"
cd "${build}"
defines="-DEM_CORE=1 -DNMM_CORE=0 -DRWORDSIZE=4 -DIWORDSIZE=4 -DDWORDSIZE=8 -DLWORDSIZE=4 -DWRF_CHEM=1"
free="-ffree-form -ffree-line-length-none -fallow-argument-mismatch"
fc="gfortran -c -O0 -cpp ${defines} ${free} -I ${build}"

: > undefined-O0.txt
guard() {
    nm -u "$1" | sed 's/^ *//' | sort > "undefined-$1.txt"
    cat "undefined-$1.txt" >> undefined-O0.txt
    if grep -q '_ZGV' "undefined-$1.txt"; then
        echo "-O0 object $1 pulled in a libmvec vector symbol" >&2
        exit 4
    fi
}
${fc} "${here}/stub_radm2emis.F90"; guard stub_radm2emis.o
${fc} "${here}/oracle_io.F90"; guard oracle_io.o
objs=(stub_radm2emis.o oracle_io.o)
for rel in share/module_model_constants.F chem/module_data_radm2.F chem/module_data_sorgam.F; do
    obj=$(basename "${rel}" .F).o
    ${fc} -o "${obj}" "${src}/${rel}"
    guard "${obj}"
    objs+=("${obj}")
done

extract() {  # print routine $2 of file $1 from its header line to its END line
    awk -v want="$2" '
        function norm(s) { s = tolower(s); gsub(/\r/, "", s); gsub(/^[ \t]+/, "", s); return s }
        {
            l = norm($0)
            if (!inside && l ~ /^((real|integer)[^ \t]*[ \t]+)?(subroutine|function)[ \t]+/) {
                t = l; sub(/^.*(subroutine|function)[ \t]+/, "", t); sub(/[ \t(].*$/, "", t)
                if (t == want) inside = 1
            }
            if (inside) {
                print $0
                if (l ~ /^end[ \t]*(subroutine|function)/) { found = 1; exit }
            }
        }
        END { if (!found) exit 7 }' "$1"
}
out=sorgam_emiss_extract.F90
{
    echo "! GENERATED by tools/chem_wrf471_oracle/radm2emis/build.sh from chem/module_aerosols_sorgam.F."
    echo "module module_aerosols_sorgam"
    cat "${here}/prelude.inc"
    echo "contains"
} > "${out}"
while read -r name; do
    name="${name%%#*}"; name="$(echo "${name}" | xargs)"
    [[ -z "${name}" ]] && continue
    extract "${src}/chem/module_aerosols_sorgam.F" "${name}" >> "${out}" || {
        echo "routine ${name} not found" >&2; exit 7; }
done < "${here}/routines.list"
echo "end module module_aerosols_sorgam" >> "${out}"
${fc} -o sorgam_emiss_extract.o "${out}"; guard sorgam_emiss_extract.o
objs+=(sorgam_emiss_extract.o)
${fc} -o module_emissions_anthropogenics.o "${src}/chem/module_emissions_anthropogenics.F"
guard module_emissions_anthropogenics.o
objs+=(module_emissions_anthropogenics.o)

printf 'subroutine control(x, n)\n integer :: n, i\n real :: x(n)\n do i = 1, n\n  x(i) = exp(x(i))\n end do\nend subroutine\n' > control.f90
gfortran -c -Ofast -ftree-vectorize -o control.o control.f90
nm -u control.o | grep -q '_ZGV' || {
    echo "libmvec positive control produced no _ZGV symbol; the guard is vacuous" >&2; exit 5; }

for driver in "${here}"/run_*.F90; do
    name=$(basename "${driver}" .F90)
    ${fc} -o "${name}.o" "${driver}"; guard "${name}.o"
    gfortran -o "${name}" "${objs[@]}" "${name}.o"
    rm -rf "${fixtures:?}/${name#run_}"
    mkdir -p "${fixtures}/${name#run_}"
    "./${name}" "${fixtures}/${name#run_}" > "${name}-stdout.txt"
    (cd "${fixtures}/${name#run_}" && find . \( -name '*.bin' -o -name MANIFEST.txt \) \
        | LC_ALL=C sort | xargs sha256sum > oracle-sha256sums.txt)
done

{
    echo "# gfortran: $(gfortran --version | head -1)"
    echo "# glibc:    $(ldd --version 2>&1 | head -1 || true)"
    echo "# -O0 libm symbols the reference calls:"
    grep -E 'expf|powf|logf|log10f|sqrtf|exp$|log$|pow$|__powi|_ZGV' undefined-O0.txt | sort -u || true
} > libm-report.txt
cat "${here}/SOURCES.sha256" > oracle-source-sha256sums.txt
(cd "${here}" && sha256sum ./*.F90 ./*.inc ./*.list ./build.sh | sed 's#  \./#  tools/chem_wrf471_oracle/radm2emis/#') >> oracle-source-sha256sums.txt
echo "radm2emis oracle built in ${build}; fixtures in ${fixtures}"
