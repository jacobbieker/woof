"""Exact constants for woof/backend/metal/f64_df64.h.

Every constant is computed with Python integers and fractions (pi by
Machin's formula, log 2 and log 10 by atanh series, all to 1600 bits), then
split into binary32 pieces: a double-float (hi, lo) pair is hi = RN32(v),
lo = RN32(v - hi).  Run it to print the C block the header carries; the
test ``tests/test_metal_df64.py`` checks the header's block against it.

    pixi run -e default python tools/df64_constants.py
"""
from __future__ import annotations

import struct
from fractions import Fraction

BITS = 1600
ONE = 1 << BITS


def _atan_inv(n: int) -> int:
    """atan(1/n) * 2^BITS."""
    total, term, k, n2 = 0, ONE // n, 0, n * n
    while term:
        total += term // (2 * k + 1) if k % 2 == 0 else -(term // (2 * k + 1))
        term //= n2
        k += 1
    return total


def _atanh_inv(n: int) -> int:
    """atanh(1/n) * 2^BITS."""
    total, term, k, n2 = 0, ONE // n, 0, n * n
    while term:
        total += term // (2 * k + 1)
        term //= n2
        k += 1
    return total


PI = Fraction(4 * (4 * _atan_inv(5) - _atan_inv(239)), ONE)
LN2 = Fraction(2 * _atanh_inv(3), ONE)
# log 10 = 3 log 2 + log(5/4) = 3 log 2 + 2 atanh(1/9)
LN10 = 3 * LN2 + Fraction(2 * _atanh_inv(9), ONE)


def f32(v: Fraction) -> float:
    """v rounded to the nearest binary32 (ties to even), as a Python float."""
    if v == 0:
        return 0.0
    sign = -1 if v < 0 else 1
    v = abs(v)
    e = v.numerator.bit_length() - v.denominator.bit_length()
    while Fraction(2) ** e > v:
        e -= 1
    while Fraction(2) ** (e + 1) <= v:
        e += 1
    scale = Fraction(2) ** (e - 23)
    q, r = divmod(v / scale, 1)
    q = int(q)
    if r > Fraction(1, 2) or (r == Fraction(1, 2) and q & 1):
        q += 1
    return sign * float(Fraction(q) * scale)


def lit(x: float) -> str:
    s = "%.9g" % x
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def pair(v: Fraction) -> tuple[float, float]:
    hi = f32(v)
    return hi, f32(v - Fraction(hi))


def triple_short(v: Fraction, bits: int = 12) -> tuple[float, float, float]:
    """v = c1 + c2 + c3 with c1 carrying only ``bits`` significant bits, so
    k * c1 is exact for |k| < 2^(24 - bits)."""
    e = v.numerator.bit_length() - v.denominator.bit_length()
    scale = Fraction(2) ** (e - bits + 1)
    c1 = float(Fraction(round(v / scale)) * scale)
    c2 = f32(v - Fraction(c1))
    c3 = f32(v - Fraction(c1) - Fraction(c2))
    return c1, c2, c3


def two_over_pi_words(n: int = 20) -> list[int]:
    """Bits 1 .. 64n of 2/pi after the binary point, 64 per word, MSB first."""
    x = 2 / PI
    words = []
    for _ in range(n):
        x *= 2 ** 64
        w = int(x)
        words.append(w)
        x -= w
    return words


def atan_frac(x: Fraction) -> Fraction:
    """atan(x), 0 < x <= 1, to 2^-BITS: x = 1 is pi/4; otherwise the Taylor
    series on scaled integers (x <= 7/8 converges in a few hundred terms)."""
    if x == 1:
        return PI / 4
    p, q = x.numerator, x.denominator
    term = ONE * p // q
    total, k = 0, 0
    while term:
        total += term // (2 * k + 1) if k % 2 == 0 else -(term // (2 * k + 1))
        term = term * p * p // (q * q)
        k += 1
    return Fraction(total, ONE)


def fact(n: int) -> int:
    out = 1
    for k in range(2, n + 1):
        out *= k
    return out


def block() -> str:
    lines = ["// ---- generated by tools/df64_constants.py: do not edit by hand"]

    def df(name, v):
        hi, lo = pair(v)
        lines.append(f"#define {name} df_make({lit(hi)}, {lit(lo)})")

    c1, c2, c3 = triple_short(LN2)
    lines.append(f"#define DF_LN2_C1 {lit(c1)}")
    lines.append(f"#define DF_LN2_C2 {lit(c2)}")
    lines.append(f"#define DF_LN2_C3 {lit(c3)}")
    lines.append(f"#define DF_INV_LN2_F {lit(f32(1 / LN2))}")
    df("DF_LN2", LN2)
    df("DF_INV_LN2", 1 / LN2)
    df("DF_INV_LN10", 1 / LN10)
    df("DF_PI", PI)
    df("DF_PI_2", PI / 2)
    df("DF_PI_4", PI / 4)
    df("DF_3PI_4", 3 * PI / 4)
    # expm1 Taylor coefficients 1/n!, n = 2..9
    for n in range(2, 10):
        df(f"DF_INV_FACT{n}", Fraction(1, fact(n)))
    # 2 atanh(z) = 2z + 2z^3/3 + ...: coefficients 2/(2n+1), n = 1..10
    for n in range(1, 11):
        df(f"DF_ATANH{n}", Fraction(2, 2 * n + 1))
    # sin: (-1)^n/(2n+1)!, cos: (-1)^n/(2n)!, n = 1..9
    for n in range(1, 10):
        df(f"DF_SIN{n}", Fraction((-1) ** n, fact(2 * n + 1)))
        df(f"DF_COS{n}", Fraction((-1) ** n, fact(2 * n)))
    # atan: (-1)^n/(2n+1), n = 1..11
    for n in range(1, 12):
        df(f"DF_ATAN{n}", Fraction((-1) ** n, 2 * n + 1))
    # atan(k/8), k = 0..8, as two binary32 tables (hi, lo)
    table = [pair(atan_frac(Fraction(k, 8))) if k else (0.0, 0.0) for k in range(9)]
    lines.append("#define DF_ATAN_K_HI " + ", ".join(lit(h) for h, _ in table))
    lines.append("#define DF_ATAN_K_LO " + ", ".join(lit(l) for _, l in table))
    words = two_over_pi_words()
    body = ", ".join(f"0x{w:016X}UL" for w in words)
    lines.append(f"#define DF_TWO_OVER_PI_WORDS {body}")
    lines.append("// ---- end generated")
    return "\n".join(lines)


if __name__ == "__main__":
    print(block())
