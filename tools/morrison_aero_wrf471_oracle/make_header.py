#!/usr/bin/env python3
"""Turn build.sh's constants-aero.txt into woof/core/kernels/
morrison_aero_constants.cuh: the words WRF v4.7.1's
MORR_TWO_MOMENT_INIT_AERO computes that the aerosol-aware Morrison unit
(mp_physics = 40) reads on top of mp_physics = 10's morrison_constants.cuh,
plus DERF1's coefficient tables from the module's own DATA statements.

Every scalar MORR_TWO_MOMENT_INIT word both inits compute is compared:
only DCS (350 um, "TWG Increase from 150.E-6") and the three words WRF
derives from it (CONS21, CONS22 and LAMMINI) may differ from mp_physics =
10's, and those four are redefined here.  Anything else differing is
refused.

usage: make_header.py constants-aero.txt MP10_CONSTANTS.txt
                      module_mp_morr_two_moment_aero.F OUTPUT.cuh
"""
import re
import struct
import sys

REDEFINED = ("DCS", "CONS21", "CONS22", "LAMMINI")
SCALARS = ("aten_pamdm", "alogaten_pamdm", "alog2_pamdm", "alog3_pamdm",
           "third_pamdm", "sq2_pamdm", "real_tiny", "t0")
ARRAYS = ("alogsig_pamdm", "exp45logsig_pamdm", "smcrit_pamdm", "f1_pamdm",
          "f2_pamdm", "hygro_aer", "density_aer", "dispersion_aer",
          "num_to_mass_aer", "ccnfact_pamdm")


def f32(word):
    v = struct.unpack("<f", struct.pack("<I", int(word, 16)))[0]
    return v.hex() + "f" if v != 0.0 else "0.0f"


def read(path):
    data = {}
    for line in open(path):
        kind, name, mode, i, word = line.split()
        data[(kind, name, int(mode), int(i))] = word
    return data


def derf1_tables(fortran):
    src = open(fortran, encoding="latin-1").read()
    body = src[src.index("REAL FUNCTION DERF1"):src.index("END FUNCTION DERF1")]
    tables = {}
    for name in ("A", "B"):
        values = []
        for m in re.finditer(r"DATA\s*(?:\(" + name + r"\(I\)[^/]*|" + name
                             + r")\s*/([^/]*)/", body):
            values += re.findall(r"-?\d+\.\d+E0", m.group(1))
        if len(values) != 65:
            raise SystemExit(f"DERF1 {name}: {len(values)} coefficients")
        # REAL literals: the decimal string rounded once to binary32, as
        # gfortran and NVRTC both do.
        tables[name] = [v + "f" for v in values]
    return tables


def main(argv):
    aero = read(argv[1])
    mp10 = read(argv[2])
    for key, word in mp10.items():
        if key not in aero:
            raise SystemExit(f"aero dump lacks {key}")
        if aero[key] != word and key[1] not in REDEFINED:
            raise SystemExit(f"{key} differs from mp_physics = 10: "
                             f"{word} vs {aero[key]}")
    out = ["// GENERATED by tools/morrison_aero_wrf471_oracle/make_header.py",
           "// from WRF v4.7.1 MORR_TWO_MOMENT_INIT_AERO's own words",
           "// (tools/morrison_aero_wrf471_oracle/build.sh) and DERF1's DATA.",
           "// Do not edit: regenerate.  Every other init word equals",
           "// mp_physics = 10's (morrison_constants.cuh, checked).",
           "#pragma once", "#define MORR_AERO 1", ""]
    for name in REDEFINED:
        words = {aero[("R", name, m, 1)] for m in (0, 1)}
        if len(words) != 1:
            raise SystemExit(f"{name} depends on morr_rimed_ice")
        out += [f"#undef MO_{name.upper()}",
                f"#define MO_{name.upper()} ({f32(words.pop())})"]
    for name in SCALARS:
        out.append(f"#define MA_{name.upper()} "
                   f"({f32(aero[('R', name, 0, 1)])})")
    for name in ARRAYS:
        n = max(i for (k, nm, m, i) in aero if nm == name and m == 0)
        for i in range(1, n + 1):
            if aero[("R", name, 0, i)] != aero[("R", name, 1, i)]:
                raise SystemExit(f"{name} depends on morr_rimed_ice")
        body = ", ".join(f32(aero[("R", name, 0, i)]) for i in range(1, n + 1))
        out.append(f"__device__ __constant__ float ma_{name}[{n}] = {{{body}}};")
    for name, values in derf1_tables(argv[3]).items():
        out.append(f"__device__ __constant__ float ma_derf1_{name.lower()}"
                   f"[65] = {{{', '.join(values)}}};")
    open(argv[4], "w", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
