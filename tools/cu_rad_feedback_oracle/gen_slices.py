"""Slice WRF v4.7.1's radiation-cloud lines VERBATIM into a compilable module.

module_radiation_driver.F cannot be compiled on its own (it USEs every
radiation scheme and the WRF frame), so the oracle takes the exact lines
that form the cloud radiation reads when a cumulus scheme feeds it, each a
complete statement block, and wraps them in subroutines whose only added
text is the dummy-argument declarations:

  slice_icloud_cu1   :1264-1281  QC += QC_CU, QI += QI_CU     (ICLOUD_CU = 1)
  slice_kf_merge     :1337-1348  the CLDFRA_CU merge          (ICLOUD_CU = 2)
  slice_deng         :1566-1575  MAX(CLDFRA_SH, CLDFRA), QC += CW_RAD
  cal_cldfra1        :3761-3986  the ICLOUD = 1 cloud fraction, the whole
                                 subroutine
  cal_cldfra2        :3676-3749  the ICLOUD = 2 cloud fraction

The order the driver program calls them in is module_radiation_driver.F's
own: the ICLOUD_CU = 1 sum (:1264), CLDFRA = 0 (:1310-1316), the ICLOUD
branch's cal_cldfra1 (:1326) followed at once by the KF merge (:1333-1348)
or cal_cldfra2 (:1652), then the Deng block (:1566).  The MYNN boundary-layer
merge (:1385-1406) and the CAMMGMP/KF-CuP/BMJ blocks are not sliced: the
oracle's cases run icloud_bl = 0 and none of those schemes.

    python gen_slices.py WRF_SOURCE_ROOT OUT.F90
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

PINNED_SHA256 = (
    "779875651512709c47d50ef6c1e1216ad94726f1996c5e45a0db8eb800733ffa")
SLICES = {
    "icloud_cu1": (1264, 1281),
    "kf_merge": (1337, 1348),
    "deng": (1566, 1575),
    "cal_cldfra1": (3761, 3986),
    "cal_cldfra2": (3676, 3749),
}
#: The first and last text of each slice, so a line shift fails the build.
ANCHORS = {
    "icloud_cu1": ("IF ( F_QC .AND. icloud_cu .EQ. 1 ) THEN", "ENDIF"),
    "kf_merge": ("DO j = jts,jte", "ENDDO"),
    "deng": ("IF( shcu_physics == 5 ) THEN", "ENDIF"),
    "cal_cldfra1": ("SUBROUTINE cal_cldfra1(", "END SUBROUTINE cal_cldfra1"),
    "cal_cldfra2": ("SUBROUTINE cal_cldfra2(", "END SUBROUTINE cal_cldfra2"),
}

DIMS = """   INTEGER, INTENT(IN) :: ims,ime, jms,jme, kms,kme, its,ite, jts,jte, kts,kte
   INTEGER :: i, j, k
"""


def main(root: str, out: str) -> None:
    path = Path(root, "phys", "module_radiation_driver.F")
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != PINNED_SHA256:
        raise SystemExit(f"{path} is {actual}, not the pinned {PINNED_SHA256}")
    lines = data.decode("utf-8").splitlines()
    text = {}
    for name, (first, last) in SLICES.items():
        block = lines[first - 1:last]
        head, tail = ANCHORS[name]
        if head not in block[0] or tail not in block[-1]:
            raise SystemExit(f"slice {name} {first}-{last} moved: "
                             f"{block[0]!r} ... {block[-1]!r}")
        text[name] = "\n".join(block)
    body = f"""! GENERATED by tools/cu_rad_feedback_oracle/gen_slices.py from WRF v4.7.1
! phys/module_radiation_driver.F (sha256 {PINNED_SHA256}).
! Every executable line below is a verbatim slice of that file; only the
! SUBROUTINE statements and the dummy-argument declarations are added.
MODULE wrf_rad_cloud_slices
  IMPLICIT NONE
CONTAINS
  SUBROUTINE slice_icloud_cu1(qc, qi, qc_cu, qi_cu, F_QC, F_QI, icloud_cu, &
                              ims,ime, jms,jme, kms,kme, its,ite, jts,jte, kts,kte)
{DIMS}   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(INOUT) :: qc, qi
   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(IN) :: qc_cu, qi_cu
   LOGICAL, INTENT(IN) :: F_QC, F_QI
   INTEGER, INTENT(IN) :: icloud_cu
! module_radiation_driver.F:1264-1281
{text['icloud_cu1']}
  END SUBROUTINE slice_icloud_cu1

  SUBROUTINE slice_kf_merge(CLDFRA, qc, qi, qc_cu, qi_cu, cldfra_dp, cldfra_sh, &
                            ims,ime, jms,jme, kms,kme, its,ite, jts,jte, kts,kte)
{DIMS}   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(INOUT) :: CLDFRA, qc, qi
   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(IN) :: qc_cu, qi_cu, &
                                                          cldfra_dp, cldfra_sh
   REAL, DIMENSION(ims:ime,kms:kme,jms:jme) :: cldfra_cu
! module_radiation_driver.F:1337-1348
{text['kf_merge']}
  END SUBROUTINE slice_kf_merge

  SUBROUTINE slice_deng(cldfra, qc, cldfra_sh, cw_rad, shcu_physics, &
                        ims,ime, jms,jme, kms,kme, its,ite, jts,jte, kts,kte)
{DIMS}   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(INOUT) :: cldfra, qc
   REAL, DIMENSION(ims:ime,kms:kme,jms:jme), INTENT(IN) :: cldfra_sh, cw_rad
   INTEGER, INTENT(IN) :: shcu_physics
! module_radiation_driver.F:1566-1575
{text['deng']}
  END SUBROUTINE slice_deng

! module_radiation_driver.F:3676-3749
{text['cal_cldfra2']}

! module_radiation_driver.F:3761-3986
{text['cal_cldfra1']}
END MODULE wrf_rad_cloud_slices
"""
    Path(out).write_text(body, encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
